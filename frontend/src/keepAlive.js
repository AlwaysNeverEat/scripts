// ── Heartbeat: не даём соединению с бэкендом простаивать ─────────────────────
// Фильтрация трафика в РФ бьёт по TLS-хендшейку: имя хоста в ClientHello лежит
// открытым текстом (SNI), по нему соединение и душат. Установленное соединение
// уже не трогают — имени в нём нет, всё зашифровано. Браузер держит одно
// TCP+TLS соединение на хост и гонит по нему все запросы (HTTP/2 keep-alive),
// так что дорого стоит только его прокладка.
//
// Отсюда вывод: простой — враг. Браузер закрывает незанятое keep-alive
// соединение через полминуты-минуту, и следующий запрос юзера начинается с
// нового хендшейка, то есть с лотереи. Тихий пинг /health раз в 40 секунд
// держит трубу открытой, и клик по кнопке едет по готовому соединению.
//
// Нагрузки это не создаёт: /health отвечает {ok:true} без похода в базу, а
// сервис и так не спит — его будит keep-warm workflow раз в 10 минут.

const PERIOD = 40_000;

export function startKeepAlive(pingUrl) {
    if (!pingUrl) return;

    let timer = null;

    const ping = () => {
        const sep = pingUrl.includes('?') ? '&' : '?';
        // Ошибку глотаем сознательно: не достучались — значит трубы сейчас нет,
        // и следующий запрос приложения сам разберётся. Шуметь тут нечем.
        fetch(pingUrl + sep + '_=' + Date.now(), { cache: 'no-store' }).catch(() => {});
    };

    const start = () => {
        if (timer) return;
        ping(); // сразу: вкладку только что открыли — соединение уже могло умереть
        timer = setInterval(ping, PERIOD);
    };

    const stop = () => {
        clearInterval(timer);
        timer = null;
    };

    // В фоновой вкладке греть нечего — таймеры там всё равно душит сам браузер.
    // Зато при возврате важно переустановить соединение ДО того, как юзер
    // куда-то ткнёт, иначе первый же клик упрётся в новый хендшейк.
    document.addEventListener('visibilitychange', () => {
        if (document.hidden) stop(); else start();
    });

    if (!document.hidden) start();
}
