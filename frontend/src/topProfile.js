// ─────────────────────────────────────────────────────────────────────────────
// Строка любого топа открывает профиль — ОДНО место на весь сайт.
//
// На вкладке «Топ» так было с самого начала (frontend/src/top.js): щёлкнул по
// строке — уехал на #/user/<id>. А мини-топы пасхалок этого не умели, и
// получалось странно: те же коллеги, те же аватарки, но в одном списке имя
// кликается, а в другом нет. Теперь переход один на все списки сразу —
// месячный топ, мини-топы тетриса, тройки, пасьянса, рогалика и маджонга,
// таблицы бильярда, дурака и морского боя.
//
// Разметку строк каждая игра рисует свою (у тетриса .tet-top-row, у пасьянса
// .sol-top-row и так далее — подписи в них разные), поэтому общими сделаны не
// строки, а ДВЕ МЕЛОЧИ: атрибуты, которыми строка помечается как ведущая в
// профиль, и обработчик клика. Заводить ради этого общий компонент строки
// значило бы переписать шесть готовых окон ради одного data-атрибута.
//
// ОКНО ИГРЫ ПРИ ПЕРЕХОДЕ ЗАКРЫВАЕТСЯ, и иначе нельзя: профиль — обычная
// страница под окном, и оставшееся сверху окно накрыло бы её собой. Партия при
// этом не теряется: все игры запоминают недоигранное при закрытии (см. `saved`
// в tetris.js, solitaire.js, mahjong.js и соседях) — вернуться и доиграть можно
// оттуда же.
//
// Своя строка («Ваше время», «Ваш результат») в профиль не ведёт: у неё нет id,
// а вести человека в его собственный профиль из мини-топа незачем — он там и
// так бывает чаще всего.
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Атрибуты строки топа, ведущей в профиль. Строка без id (своя, отдельная)
 * получает пустую строку и остаётся обычным блоком.
 */
export function profileRowAttrs(row) {
    return row?.id ? ` data-profile="${row.id}" title="Открыть профиль"` : '';
}

/**
 * Развесить переходы по всем строкам внутри `box`.
 *
 * `close` — закрыть окно игры (передаётся из самой игры). Вызывается ДО смены
 * адреса: сначала убираем окно, потом уезжаем, иначе на долю секунды видно
 * профиль под чужим окном.
 */
export function bindProfileRows(box, close) {
    box.querySelectorAll('[data-profile]').forEach(el => {
        el.onclick = () => {
            const id = el.dataset.profile;
            close?.();
            location.hash = '#/user/' + id;
        };
    });
}
