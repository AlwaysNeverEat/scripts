// ─────────────────────────────────────────────────────────────────────────────
// ПЕРЕТЕКАЮЩИЙ ТЕКСТ — одно место на весь сайт.
//
// Обычная запись в textContent меняет надпись СКАЧКОМ: старая строка исчезает,
// новая появляется, и глазу нечего проследить — ровно тот же довод, по которому
// у переключателей появилась едущая пилюля (segmented.js). Здесь то же самое, но
// внутри строки: общие куски остаются на месте, ушедшие уезжают, пришедшие
// приезжают, а ЦИФРЫ ПЕРЕКАТЫВАЮТСЯ ПО РАЗРЯДАМ — «15 июня» → «16 марта»
// меняет то, что действительно изменилось, а «сентября 2026» стоит как стояло.
//
// Работу делает torph (MIT, без зависимостей, github.com/lochie/torph). Свой
// такой писать незачем: там сегментация через Intl.Segmenter, разбор числа по
// разрядам и уважение к prefers-reduced-motion — это неделя работы и вечная
// возня с локалями.
//
// ЧАНК ПРИЕЗЖАЕТ ПО ТРЕБОВАНИЮ, как игры и трубы: библиотека нужна на профиле, а
// её тридцать килобайт в первой загрузке сайта не нужны никому. Пока чанк едет,
// текст ставится обычной записью — то есть худшее, что бывает при медленной
// сети, это «как было раньше». Отвалилась загрузка совсем (офлайн, блокировщик)
// — тоже: надпись меняется скачком, но меняется.
//
// ГДЕ ЭТО УМЕСТНО. Только там, где НОВАЯ надпись — та же по смыслу, что старая:
// период показанного куска года, счётчик, место в топе. Там, где текст меняется
// на посторонний, перетекание врёт — оно показывает связь, которой нет.
// ─────────────────────────────────────────────────────────────────────────────

// Пружина сайта — та же, что у едущей пилюли и у ленты активности
// (cubic-bezier(.32, .72, 0, 1) в style.css). Движение по сайту должно быть
// одно, иначе новая анимация читается как чужая.
const EASE = 'cubic-bezier(.32, .72, 0, 1)';

// Короче стандартных 400 мс сознательно: подпись периода меняется НА КАЖДОМ
// шаге ведения карты года, то есть по нескольку раз в секунду. С длинной
// анимацией строка не успевает встать и превращается в кашу.
const DURATION = 260;

const morphs = new WeakMap();   // узел → его экземпляр
const starting = new WeakSet(); // узлы, которым экземпляр уже заказан
let loader = null;              // одна загрузка чанка на весь сайт

// null, если библиотека не приехала: вызвавший уже поставил текст обычной
// записью, и это рабочее состояние, а не поломка.
function load() {
    if (!loader) {
        loader = import('torph')
            .then(m => m.TextMorph)
            .catch(() => null);
    }
    return loader;
}

/**
 * Ставит элементу текст, перетекая из старого. До приезда библиотеки (и без
 * неё) — обычная запись в textContent.
 *
 * Экземпляр помнится ПО УЗЛУ (WeakMap): разделы сайта перерисовываются через
 * innerHTML, старый узел выбрасывается вместе со своим экземпляром, а новый
 * заводит свой. Ничего снимать руками не надо.
 */
export function morphText(el, text) {
    if (!el) return;
    const value = String(text ?? '');

    const morph = morphs.get(el);
    if (morph) { morph.update(value); return; }

    el.textContent = value;
    if (starting.has(el)) return;
    starting.add(el);

    load().then((TextMorph) => {
        // Узел мог уехать со страницы, пока ехал чанк, — тогда и морфить нечего.
        if (!TextMorph || !el.isConnected || morphs.has(el)) return;
        const morph = new TextMorph({
            element: el,
            locale: 'ru',        // сегментация русских слов, а не английских
            ease: EASE,
            duration: DURATION,
        });
        // Первый update — не анимация, а «запомни, что сейчас на экране»:
        // строка уже стоит в узле, перетекать ей неоткуда.
        morph.update(el.textContent);
        morphs.set(el, morph);
    });
}
