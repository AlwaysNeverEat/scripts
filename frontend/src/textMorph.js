// ─────────────────────────────────────────────────────────────────────────────
// ПЕРЕТЕКАЮЩИЙ ТЕКСТ — одно место на весь сайт.
//
// Обычная запись в textContent меняет надпись СКАЧКОМ: старая строка исчезает,
// новая появляется, и глазу нечего проследить — ровно тот же довод, по которому
// у переключателей появилась едущая пилюля (segmented.js). Здесь то же самое, но
// внутри строки: общие куски остаются на месте, ушедшие уезжают, пришедшие
// приезжают, а ЦИФРЫ ПЕРЕКАТЫВАЮТСЯ ПО РАЗРЯДАМ — «490» → «118» крутит сотни и
// десятки, а «15 июня — 7 сентября 2026» → «16 марта — 7 сентября 2026» трогает
// только начало строки.
//
// Работу делает torph (MIT, без зависимостей, github.com/lochie/torph). Свой
// такой писать незачем: там сегментация через Intl.Segmenter, разбор числа по
// разрядам и уважение к prefers-reduced-motion — это неделя работы и вечная
// возня с локалями.
//
// ЧАНК ПРИЕЗЖАЕТ ПО ТРЕБОВАНИЮ, как игры и трубы: библиотека нужна не на первом
// экране, а её тридцать килобайт в первой загрузке сайта не нужны никому. Пока
// чанк едет, текст ставится обычной записью — то есть худшее, что бывает при
// медленной сети, это «как было раньше». Отвалилась загрузка совсем (офлайн,
// блокировщик) — тоже: надпись меняется скачком, но меняется.
//
// ── ДВА СПОСОБА ПОДКЛЮЧИТЬ ───────────────────────────────────────────────────
//
// 1. ИМПЕРАТИВНО, когда узел живёт долго, а текст ему меняют из кода:
//
//        morphText(el, `${count} ${recordsWord(count)}`);
//
// 2. АТРИБУТОМ, когда кусок разметки ПЕРЕРИСОВЫВАЕТСЯ ЦЕЛИКОМ через innerHTML
//    (записи, калькулятор, топ — так устроена половина сайта):
//
//        <b data-morph="rc-free">${free}</b>
//
//    Тут узел каждый раз новый, и помнить прошлую надпись по узлу бессмысленно —
//    её помнят ПО ИМЕНИ, как segmented.js помнит положение пилюли по имени
//    группы. Новый узел с тем же именем перетекает из того, что стояло в
//    прошлом, а не появляется скачком. Имя обязано быть уникальным на странице:
//    два узла с одним именем будут перетекать друг из друга.
//
//    Включается один раз из main.js — initTextMorph(); дальше наблюдатель за
//    документом подхватывает новую разметку сам, как у капсул.
//
// ── ГДЕ ЭТО УМЕСТНО ──────────────────────────────────────────────────────────
//
// Только там, где НОВАЯ надпись — та же по смыслу, что старая: счётчик, период,
// место в топе, цена, статус. Там, где текст меняется на посторонний (одна
// новость сменилась другой), перетекание врёт — оно показывает связь, которой
// нет, и читается как поломка.
//
// ПОЛЕ ВВОДА так не морфится и не будет: <input> рисует значение сам, внутрь
// него ничего не положить. Перетекать может только ЗЕРКАЛО поля — отдельный
// узел, показывающий то же значение (у torph для этого есть cursorIndex:
// пока человек печатает, разряды не переставляются, а вставляется набранный
// знак). Понадобится — добавим сюда же.
// ─────────────────────────────────────────────────────────────────────────────

// Пружина сайта — та же, что у едущей пилюли и у ленты активности
// (cubic-bezier(.32, .72, 0, 1) в style.css). Движение по сайту должно быть
// одно, иначе новая анимация читается как чужая.
const EASE = 'cubic-bezier(.32, .72, 0, 1)';

// Короче стандартных 400 мс сознательно: подпись периода в ленте меняется НА
// КАЖДОМ шаге ведения карты года, то есть по нескольку раз в секунду. С длинной
// анимацией строка не успевает встать и превращается в кашу.
const DURATION = 260;

const READY = 'data-morph-ready';   // на этом узле перетекание уже налажено
const morphs = new WeakMap();   // узел → его экземпляр
const starting = new WeakSet(); // узлы, которым экземпляр уже заказан
const lastText = new Map();     // имя из data-morph → что стояло в прошлый раз
let loader = null;              // одна загрузка чанка на весь сайт
let Morph = null;               // приехавший класс, чтобы не ждать промис лишний раз

// null, если библиотека не приехала: вызвавший уже поставил текст обычной
// записью, и это рабочее состояние, а не поломка.
function load() {
    if (!loader) {
        loader = import('torph')
            .then((m) => { Morph = m.TextMorph; return Morph; })
            .catch(() => null);
    }
    return loader;
}

// Заводит экземпляр на узле. Текст в узле к этому моменту уже стоит — он и
// становится точкой, из которой перетекать в следующий раз.
function attach(el, opts, TextMorph) {
    if (!TextMorph || !el.isConnected || morphs.has(el)) return null;
    const morph = new TextMorph({
        element: el,
        locale: 'ru',        // сегментация русских слов, а не английских
        ease: EASE,
        duration: DURATION,
        ...opts,
    });
    // Первый update — не анимация, а «запомни, что сейчас на экране»:
    // строка уже стоит в узле, перетекать ей неоткуда.
    morph.update(el.textContent);
    morphs.set(el, morph);
    return morph;
}

/**
 * Ставит элементу текст, перетекая из старого. До приезда библиотеки (и без
 * неё) — обычная запись в textContent.
 *
 * opts применяются при СОЗДАНИИ экземпляра (duration, ease, scale, numbers);
 * менять их на лету нельзя — узлу нужен новый экземпляр.
 *
 * Экземпляр помнится ПО УЗЛУ (WeakMap): старый узел выбрасывается вместе со
 * своим экземпляром, снимать руками нечего.
 */
export function morphText(el, text, opts) {
    if (!el) return;
    const value = String(text ?? '');
    const name = el.dataset?.morph;
    const was = name ? lastText.get(name) : undefined;
    if (name) lastText.set(name, value);

    const morph = morphs.get(el);
    if (morph) { morph.update(value); return; }

    // Библиотека уже здесь — узел заводится ПРЯМО СЕЙЧАС, и если у его имени
    // есть прошлая надпись, он перетекает из неё: кусок разметки перерисовали
    // через innerHTML, узел новый, а число для человека то же самое и просто
    // стало другим. Тот же FLIP, что у пилюли переключателя.
    if (Morph) {
        el.textContent = was !== undefined ? was : value;
        const started = attach(el, opts, Morph);
        if (started) started.update(value);
        else el.textContent = value;
        el.setAttribute(READY, '');   // атрибутному пути тут делать нечего
        return;
    }

    // Чанк ещё едет. Прошлую надпись НЕ показываем: пока он приедет (а он может
    // и не приехать), на экране висело бы старое число — это уже не анимация, а
    // враньё. Первый узел на странице поэтому появляется без перетекания.
    el.textContent = value;
    if (starting.has(el)) return;
    starting.add(el);
    // Узел мог уехать со страницы, пока ехал чанк, — тогда и морфить нечего.
    load().then(TextMorph => attach(el, opts, TextMorph));
}

// ── Атрибутный путь ──────────────────────────────────────────────────────────

// Новый узел с ЗНАКОМЫМ именем: показываем прошлую надпись, заводим экземпляр и
// тут же отпускаем к новой — обычный FLIP, как у пилюли переключателя. Иначе
// перерисовка куска через innerHTML показывала бы новое число скачком, ради
// чего всё и затевалось.
function adopt(el, TextMorph) {
    if (el.hasAttribute(READY)) return;
    el.setAttribute(READY, '');

    // Узел, которому текст уже ставят из кода, атрибутный путь не трогает
    // ВООБЩЕ: прошлую надпись за него помнит morphText, а запись в textContent
    // разнесла бы уже собранные сегменты живого экземпляра.
    if (morphs.has(el) || starting.has(el)) return;

    const name = el.dataset.morph;
    const now = el.textContent;
    const was = name ? lastText.get(name) : undefined;
    if (name) lastText.set(name, now);

    if (!TextMorph) return;
    if (was !== undefined && was !== now) el.textContent = was;
    const morph = attach(el, undefined, TextMorph);
    if (morph && el.textContent !== now) morph.update(now);
}

function scan(TextMorph, root = document) {
    for (const el of root.querySelectorAll(`[data-morph]:not([${READY}])`)) adopt(el, TextMorph);
}

let started = false;

/**
 * Включает `data-morph` на всей странице и продолжает следить за новой
 * разметкой. Зовётся один раз при старте приложения; повторные вызовы
 * безвредны.
 */
export function initTextMorph() {
    if (started) return;
    started = true;

    load().then((TextMorph) => {
        scan(TextMorph);
        // Скан отложен до кадра: перерисовка вставляет разметку кусками, и без
        // склейки мы бы бегали по документу на каждый узел (тот же приём, что в
        // segmented.js).
        let queued = false;
        new MutationObserver(() => {
            if (queued) return;
            queued = true;
            requestAnimationFrame(() => { queued = false; scan(TextMorph); });
        }).observe(document.body, { childList: true, subtree: true });
    });
}
