// ─────────────────────────────────────────────────────────────────────────────
// «Что считается совпадением по станции» — одно знание на весь раздел записей.
//
// Отсюда его берут ДВА разных места: быстрый поиск в обзоре (набрал мимо полей
// — лишние карточки пропали) и подсказки над картой станции. Правило у них
// обязано быть одним: две похожие, но разные проверки — это ровно тот случай,
// когда одна станция находится в одном месте и не находится в другом.
//
// Файл отделён от records.js не ради красоты: тот тянет за собой CSS и DOM, а
// проверка — чистая функция, и её хочется гонять тестом (stationFilter.test.js).
// ─────────────────────────────────────────────────────────────────────────────

// Латиница по расположению клавиш. Диспетчер печатает не глядя и запросто
// оставляет раскладку от гос. номера — «,hbufljdcrfz» вместо «бригадовская».
// Приводим латиницу к кириллице и совпадением считаем любую из двух: своё же
// написание кириллицей от этого не страдает.
const LAT = 'qwertyuiop[]asdfghjkl;\'zxcvbnm,.`';
const RUS = 'йцукенгшщзхъфывапролджэячсмитьбюё';

export function toCyr(q) {
    let out = '';
    for (const ch of String(q)) {
        const i = LAT.indexOf(ch);
        out += i >= 0 ? RUS[i] : ch;
    }
    return out;
}

/**
 * Совпадение по одной станции: короткое имя, метро, код перевода звонка и —
 * если разрешено флагом — полный адрес из админки. Запрос ждём уже
 * нормализованным (нижний регистр, без краёв).
 *
 * ПОЛНЫЙ АДРЕС УЧАСТВУЕТ НЕ ВСЕГДА, и это главное решение этого файла. Все
 * адреса на доске начинаются одинаково — «Санкт-Петербург, …», — поэтому по
 * ним совпадает добрая половина алфавита: «б», «е», «р», «у», «г», «с», «п»
 * оставляют на экране ВСЕ станции. Для подсказок над картой это терпимо (туда
 * набирают улицу целиком), а для быстрого поиска смертельно: он и затевался
 * ради первых двух-трёх букв.
 */
export function stationMatch(addr, meta, q, { address = true } = {}) {
    if (!q) return true;
    return String(meta?.short || '').toLowerCase().includes(q)
        || String(meta?.metro || '').toLowerCase().includes(q)
        || String(meta?.boxNo || '').includes(q)
        || (address && String(addr?.title || '').toLowerCase().includes(q));
}

/**
 * Отсев карточек обзора: list — [{ addr, meta }], query — как набрали.
 * Пустой запрос не трогает список вовсе: это не «поиск, который всегда включён»,
 * а маска, которой пользуются секундами.
 *
 * По адресу ищем только у станций, которых нет в справочнике: имени у них
 * попросту нет, и без адреса такая станция не находилась бы ничем — а пропасть
 * с доски она не должна (см. sortedStations в records.js).
 */
export function filterStations(list, query) {
    const q = String(query || '').trim().toLowerCase();
    if (!q) return list;
    const cyr = toCyr(q);
    return list.filter(({ addr, meta }) => {
        const opts = { address: !meta?.short };
        return stationMatch(addr, meta, q, opts)
            || (cyr !== q && stationMatch(addr, meta, cyr, opts));
    });
}
