-- Пасхалка «Тройка» (матч-3 на время): мини-топ внутри окна игры.
--
-- Устроена ровно как таблица тетриса (024→025), и это осознанно: у обеих
-- пасхалок результат — рекорд, а не событие дня, и обе считают партию в
-- браузере. Хранится РОВНО ОДНА строка на игрока — его лучший результат.
-- Историю партий не пишем: топ показывает рекорд, а тысячи строк «партия на
-- 300 очков» не нужны никому.
--
-- Отдельная таблица, а не общая «game_scores» с колонкой игры: у игр разные
-- показатели в подписи строки (у тетриса линии и уровень, здесь ходы, часы и
-- каскад), и общая таблица неизбежно стала бы набором полей, половина из
-- которых всегда NULL.
--
-- Присланный результат сервер проверяет на правдоподобность
-- (isPlausibleRun из shared/troika.js) — это защита от мусора, а не от
-- человека с открытой консолью; таблица пасхалки такой цены и стоит.

CREATE TABLE IF NOT EXISTS troika_scores (
  -- Ключ — сам пользователь: строка одна, и вставка «лучшего» превращается в
  -- обычный upsert без гонок за «а вдруг уже есть».
  user_id   uuid        PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
  score     int         NOT NULL,
  -- Уровень (считается от очков), сделанных ходов и убранных фишек.
  level     int         NOT NULL DEFAULT 1,
  moves     int         NOT NULL DEFAULT 0,
  tiles     int         NOT NULL DEFAULT 0,
  -- Собранные часы: именно они и держат партию на плаву, поэтому в итоге
  -- рекордной партии их видно.
  clocks    int         NOT NULL DEFAULT 0,
  -- Самая длинная цепочка рекордной партии — то, чем в этой игре хвастаются.
  -- Не «cascade»: CASCADE — ключевое слово SQL, и колонку с таким именем рано
  -- или поздно придётся заковычивать в каком-нибудь запросе.
  best_cascade int      NOT NULL DEFAULT 0,
  seconds   int         NOT NULL DEFAULT 0,
  -- Сколько партий доиграно до конца — маленькая радость в подписи «партий: N».
  games     int         NOT NULL DEFAULT 1,
  -- Когда поставлен ИМЕННО рекорд (а не последняя партия): при равном счёте в
  -- топе выше тот, кто добрался до него раньше.
  played_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS troika_scores_top_idx ON troika_scores (score DESC, played_at);
