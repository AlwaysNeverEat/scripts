-- Общая история поиска по складу (режим «Склад» на главной).
--
-- Одна строка на ЗАПРОС, а не на каждый поиск: история нужна, чтобы быстро
-- набрать то, что уже искали, и второй строкой «W 712/95» ей ничего не даёт.
-- Повтор запроса двигает строку наверх (last_at) и прибавляет uses — по ним
-- подсказки и сортируются.
--
-- История ОБЩАЯ на всех, а не своя у каждого: за одной станцией работают
-- посменно, и артикулы, которые искал напарник, нужны точно так же. Кто искал
-- последним, всё же помним (last_user_id) — на случай вопроса «откуда это
-- тут», а не для показа.
--
-- Ключ — нормализованный запрос (без лишних пробелов, в нижнем регистре):
-- «w 712/95» и «W 712/95» в CRM ищут одно и то же, и держать их двумя
-- строками значило бы показывать одну подсказку дважды. Как запрос набрали
-- в последний раз, хранится отдельно (query) — так его и показываем.

CREATE TABLE IF NOT EXISTS crm_stock_searches (
  query_norm   text        PRIMARY KEY,
  query        text        NOT NULL,
  uses         bigint      NOT NULL DEFAULT 1,
  last_user_id uuid        REFERENCES users (id) ON DELETE SET NULL,
  first_at     timestamptz NOT NULL DEFAULT now(),
  last_at      timestamptz NOT NULL DEFAULT now()
);

-- Подсказки — это «последние N», и спрашиваются они при каждом открытии режима.
CREATE INDEX IF NOT EXISTS crm_stock_searches_last_idx
  ON crm_stock_searches (last_at DESC);
