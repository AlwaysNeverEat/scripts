-- Пасхалка «Дурак»: комнаты на 2–4 игроков и таблица очков.
--
-- ЧЕМ ЭТА ПАСХАЛКА ОТЛИЧАЕТСЯ ОТ СОСЕДЕЙ. У тетриса, тройки и пасьянса (025,
-- 026, 027) сервер хранит одну строку на игрока — его рекорд, а партию считает
-- браузер. У бильярда (028) сервер ведёт партию, но позицию всё равно знают оба:
-- стол на виду, и клиент лишь сверяет отпечаток. Здесь ни то, ни другое: В КАРТЫ
-- ИГРАЮТ ЗАКРЫТЫМИ. Чужая рука и колода — тайна, и браузер, которому их отдали,
-- знает лишнее. Поэтому позиция живёт ТОЛЬКО ЗДЕСЬ, а каждому игроку уезжает его
-- вид на неё (viewFor в shared/durak.js).
--
-- Партия — ОДНА СТРОКА, а не журнал ходов: за партию их под сотню, а опрашивают
-- «не сходил ли сосед» раз в полторы секунды, и проигрывать всю партию заново на
-- каждый опрос было бы разорительно. В state лежит текущая позиция целиком.
--
-- ИГРОКИ — МАССИВ, а не два столбца p0/p1, как в бильярде: за столом бывает от
-- двух до четырёх человек, и место в массиве и есть номер места за столом.
-- Оттуда же берётся, кто чей сосед: в дураке отбивается следующий по кругу.
--
-- Партий с ботом здесь нет вовсе: они целиком в браузере и в таблицу очков не
-- идут — иначе первое место занял бы не тот, кто обыгрывает людей, а тот, кто
-- настрелял побед по Новичку.

CREATE TABLE IF NOT EXISTS durak_games (
  id         uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Хозяин комнаты: он её создал, он может начать раньше, чем соберутся все,
  -- и он же уносит её с собой, если передумал.
  host       uuid        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  -- Игроки по местам. Порядок важен: сосед слева отбивается.
  players    uuid[]      NOT NULL,
  -- Сколько мест в комнате. Партию можно начать и меньшим числом — тогда
  -- seats становится равен фактическому числу севших.
  seats      smallint    NOT NULL DEFAULT 2,
  -- podkidnoy | perevodnoy. Правила одни, но перевод меняет игру заметно, и
  -- договариваться о нём надо ДО раздачи — поэтому режим у комнаты, а не у хода.
  mode       text        NOT NULL DEFAULT 'podkidnoy',
  seed       bigint      NOT NULL,
  -- open — комната собирает людей, live — играют, done — доиграли.
  status     text        NOT NULL DEFAULT 'open',
  -- Позиция как её видит сервер (shared/durak.js, serialize). Пока комната
  -- собирается, её нет: раздавать некому, и NULL тут честнее выдуманной раздачи.
  state      jsonb,
  -- Сколько ходов сыграно. Он же — защита от двойной отправки: ход применяется,
  -- только если клиент прислал то же число (см. routes/durak.js).
  seq        int         NOT NULL DEFAULT 0,
  -- В дураке нет победителя, есть ДУРАК — тот, у кого остались карты. NULL при
  -- status = 'done' означает ничью (вышли разом или карты пошли по кругу).
  loser      uuid        REFERENCES users (id) ON DELETE SET NULL,
  -- Чем кончилось: out, draw, stall, resign, timeout.
  reason     text        NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  -- Когда сделан последний ход. По нему брошенная партия закрывается: без этого
  -- проигрывающему выгодно просто закрыть вкладку.
  moved_at   timestamptz NOT NULL DEFAULT now()
);

-- Лобби: список открытых комнат. Их единицы, но запрос идёт на каждый опрос.
CREATE INDEX IF NOT EXISTS durak_games_open_idx ON durak_games (status, created_at) WHERE status = 'open';
-- «Мои партии»: игрок ищется в массиве, поэтому индекс GIN, а не обычный.
CREATE INDEX IF NOT EXISTS durak_games_players_idx ON durak_games USING gin (players);

CREATE TABLE IF NOT EXISTS durak_scores (
  user_id   uuid        PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
  -- Очко за партию, в которой дураком остался кто-то другой.
  wins      int         NOT NULL DEFAULT 0,
  -- Поражения не влияют на место, но ПОКАЗЫВАЮТСЯ рядом — ровно как в бильярде
  -- (028): без второго числа сыгравший сорок партий обгонял бы выигравшего
  -- восемь из десяти.
  losses    int         NOT NULL DEFAULT 0,
  played_at timestamptz NOT NULL DEFAULT now()
);

-- Место в таблице: сначала победы, при равенстве — у кого меньше поражений,
-- затем кто добрался раньше.
CREATE INDEX IF NOT EXISTS durak_scores_top_idx ON durak_scores (wins DESC, losses ASC, played_at ASC);
