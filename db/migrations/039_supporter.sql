-- Подписка «supp»: платная косметика (тема «Жидкое стекло» с настройкой цвета
-- и фона, плашка перед ником, свой цвет строки в топе). Никаких рабочих
-- возможностей за деньги: записи, калькулятор, поиск клиента и место в
-- месячном топе от подписки не зависят и зависеть не должны — купленное первое
-- место в рабочем рейтинге отняло бы его у живого коллеги.
--
-- Таблиц две, и они устроены по-разному.
--
--   supporters — одна строка на аккаунт, и она НЕ УДАЛЯЕТСЯ, когда подписка
--     кончилась. Причина в колонке theme: подобранные цвет, фон и размытие —
--     это работа человека, а не часть оплаты. Кончился месяц — тема просто
--     перестала действовать (expires_at в прошлом), продлили — вернулся тот
--     же вид, а не пустой бланк.
--
--   supporter_grants — журнал выдач. Деньги приходят мимо сайта (переводом), а
--     выдаёт подписку руками владелец, поэтому «кому, когда, на сколько и с
--     какой пометкой» больше взять негде. Строки не переписываются и не
--     удаляются: это история платежей, а не состояние.
--
-- Срок ПРОВЕРЯЕТСЯ ПРИ ЧТЕНИИ (expires_at > now()), а не гасится по крону.
-- Крона в проекте нет вовсе, и заводить его ради одной колонки не стоит:
-- «сама уберётся через месяц» — это и есть отсутствующая строка в выдаче, а не
-- отдельная работа по расписанию, которая однажды не запустится.

CREATE TABLE IF NOT EXISTS supporters (
  user_id    uuid        PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
  -- NULL = бессрочно. В коде такую подписку никто не выдаёт: бессрочная есть
  -- только у владельца, и она следует из логина (backend/src/supporter/store.js),
  -- а не из строки в базе — чтобы не пропасть вместе с восстановленным дампом.
  expires_at timestamptz,
  -- Настройки темы. Формат и границы — shared/supporterTheme.js; база их не
  -- проверяет сознательно: значения уезжают в CSS, и проверять их должен тот,
  -- кто знает, что такое правильный цвет, а не CHECK на jsonb.
  theme      jsonb       NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Плашка подписчика стоит рядом с ником в топе, в мини-топах игр и в профиле,
-- то есть выборка «активные подписчики» идёт на каждой такой странице.
CREATE INDEX IF NOT EXISTS supporters_active_idx ON supporters (expires_at);

CREATE TABLE IF NOT EXISTS supporter_grants (
  id         bigserial   PRIMARY KEY,
  user_id    uuid        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  -- Кто выдал. NULL остаётся, если выдавший аккаунт когда-нибудь удалят:
  -- запись о платеже переживает удаление учётки.
  granted_by uuid        REFERENCES users (id) ON DELETE SET NULL,
  -- 'grant' — выдали месяц, 'revoke' — сняли досрочно.
  action     text        NOT NULL DEFAULT 'grant',
  -- Каким стал срок после этого действия (у 'revoke' — NULL).
  expires_at timestamptz,
  -- Пометка владельца: чем оплачено, кто просил. Свободный текст.
  note       text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS supporter_grants_user_idx ON supporter_grants (user_id, created_at DESC);
