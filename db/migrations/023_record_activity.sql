-- Лента активности в профиле («квадратики» как на GitHub): по клетке на день
-- за последний год, яркость — от среднего числа записей в активный день.
--
-- Новых таблиц не нужно: считаем те же record_credits, что и месячный топ
-- (см. 020_record_credits.sql) — одна успешно сделанная запись = одна строка.
-- Не хватало только индекса под запрос ленты: топ ходит по (month, user_id),
-- а лента — по одному пользователю за диапазон дат, и на этом индекс из 020
-- не помогает (месяцев в году 12, пришлось бы читать их все и фильтровать).
--
-- День считаем в МСК, как и месяц зачёта, — поэтому в индексе именно
-- created_at (а не выражение с таймзоной): диапазон запроса переводится в
-- timestamptz на стороне запроса, и обычный btree по нему работает.
CREATE INDEX IF NOT EXISTS record_credits_user_day_idx
  ON record_credits (user_id, created_at);
