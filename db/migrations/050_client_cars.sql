-- Машины клиента: телефон лида → машины из нашей базы (cars).
--
-- Затевалось ещё в 036_bitrix.sql (там черновик client_cars закомментирован
-- вместе с панелью Битрикса), а пригодилось с вкладкой «Лиды»: оператор
-- находит машину клиента в калькуляторе один раз, привязывает её к открытому
-- лиду, и дальше она открывается из карточки лида кликом, а в запись сама
-- ложится «Kia Rio» в комментарий. В рабочей CRM такой связи нет вовсе.
--
-- Клиент — это ТЕЛЕФОН (11 цифр, 7XXXXXXXXXX), а не id карточки CRM: лид
-- бывает и без карточки («номера нет в CRM»), а звонит человек всегда с
-- номера. Привязки общие на всех операторов: машину клиента, найденную утром
-- одной сменой, вечером видит другая.
--
-- Машин у номера бывает несколько (семья, вторая машина) — строка на пару.
-- Отвязка удаляет строку: история «кто когда отвязал» тут никому не нужна.

CREATE TABLE IF NOT EXISTS client_cars (
  phone     text        NOT NULL,
  car_id    uuid        NOT NULL REFERENCES cars (id) ON DELETE CASCADE,
  added_by  uuid        REFERENCES users (id) ON DELETE SET NULL,
  added_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (phone, car_id)
);
