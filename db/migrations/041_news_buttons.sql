-- Кнопка внутри новостного поста: сколько раз по ней нажали.
--
-- Появилась она с постом про слияние «В Битрикс» и «Записать» в одну кнопку:
-- исчезнувшую кнопку оставили в самом посте — потыкать, если будете скучать.
-- Раз она осталась, ей нужен счётчик, иначе это просто картинка.
--
-- ХРАНИМ ПО ЧЕЛОВЕКУ, А НЕ ОДНО ЧИСЛО НА ВСЕХ, и это главное решение таблицы.
-- В посте показывается общий счётчик (сумма), и одной строки `clicks = N` на
-- него хватило бы с запасом. Но тогда «кто сколько нажал» узнать было бы
-- неоткуда — а на этом счётчике однажды встанет секретная ачивка, и
-- достижения в этом проекте считаются ОТ ФАКТОВ, а не инкрементом «+1 к
-- ачивке» (см. шапку backend/src/achievements/achievements.js). Одна строка на
-- человека — и факт есть, и сумма берётся из неё же.
--
-- Строк тут максимум «людей × кнопок», то есть десятки: нажатия копятся в
-- своей строке, а не пишутся историей. История нажатий на кнопку-пасхалку не
-- нужна никому, зато это тысячи строк за один скучный вечер.
--
-- button_id — свой у каждой кнопки: пост с кнопкой уже не один раз захочется
-- повторить, а разводить под каждую свою таблицу незачем. Список известных
-- кнопок — в backend/src/news/buttons.js (чужой id в базу не попадает).

CREATE TABLE IF NOT EXISTS news_button_clicks (
  button_id text        NOT NULL,
  user_id   uuid        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  clicks    bigint      NOT NULL DEFAULT 0,
  -- Когда нажали впервые и когда в последний раз: на «первого нажавшего»
  -- ачивку однажды тоже захотят, а задним числом эту дату не восстановить.
  first_at  timestamptz NOT NULL DEFAULT now(),
  last_at   timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (button_id, user_id)
);

-- Общий счётчик — это SUM(clicks) по кнопке, и он спрашивается на каждом
-- открытии поста.
CREATE INDEX IF NOT EXISTS news_button_clicks_button_idx
  ON news_button_clicks (button_id);
