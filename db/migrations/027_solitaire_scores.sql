-- Пасхалка «Пасьянс» (косынка): мини-топ внутри окна игры.
--
-- Устроена как таблицы тетриса и тройки (025, 026), и по той же причине:
-- партия считается в браузере, а серверу остаётся ОДНА строка на игрока — его
-- рекорд. Историю партий не пишем: топ показывает лучшее, а тысячи строк
-- «разложил за девять минут» не нужны никому.
--
-- РЕКОРД ЗДЕСЬ — МИНИМУМ, А НЕ МАКСИМУМ: соревнуются временем, за которое
-- партия разложена. Отсюда все отличия от соседних таблиц — LEAST вместо
-- GREATEST в upsert и ASC в индексе.
--
-- В таблицу попадают ТОЛЬКО выигранные партии: у брошенной раскладки времени
-- нет — она не «медленная», она просто не доиграна, и в топ по времени её не
-- поставить ни на какое место.
--
-- Присланный результат сервер проверяет на правдоподобность (isPlausibleRun из
-- shared/solitaire.js) — это защита от мусора, а не от человека с открытой
-- консолью; таблица пасхалки такой цены и стоит.

CREATE TABLE IF NOT EXISTS solitaire_scores (
  -- Ключ — сам пользователь: строка одна, и вставка «лучшего» превращается в
  -- обычный upsert без гонок за «а вдруг уже есть».
  user_id   uuid        PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
  -- Время рекордной партии в секундах — то, чем меряется место в топе.
  seconds   int         NOT NULL,
  -- Ходов в рекордной партии: перенос стопки, карта из колоды и каждая карта
  -- автосбора. Ими и меряется «повезло с раздачей или разбирал руками».
  moves     int         NOT NULL DEFAULT 0,
  -- Сколько раз в рекордной партии пришлось переложить колоду заново.
  redeals   int         NOT NULL DEFAULT 0,
  -- Сколько партий всего разложено — маленькая радость в подписи «разложено: N».
  wins      int         NOT NULL DEFAULT 1,
  -- Когда поставлен ИМЕННО рекорд (а не последняя партия): при равном времени в
  -- топе выше тот, кто добрался до него раньше.
  played_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS solitaire_scores_top_idx ON solitaire_scores (seconds, played_at);
