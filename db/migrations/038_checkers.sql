-- Пасхалка «Шашки» (русские): партии двух игроков и таблица очков.
--
-- ГДЕ ОНА СРЕДИ СОСЕДЕЙ. У тетриса, тройки, пасьянса, рогалика и маджонга
-- (025–027, 034, 037) сервер хранит одну строку на игрока — его рекорд, а партию
-- считает браузер: накрутка там портит только собственное место в топе. У
-- дурака (033) и морского боя (035) партию ВЕДЁТ сервер, потому что есть
-- закрытая информация — чужая рука и чужая расстановка. Здесь закрытого нет
-- ВООБЩЕ: доска на виду у обоих с первого хода, и viewFor в shared/checkers.js
-- поэтому нет вовсе.
--
-- Партию всё равно ведёт сервер, и причина та же, что у бильярда (028): игра
-- ПАРНАЯ, и очко, которое игрок себе приписал, отнято у живого человека. Только
-- бильярду сервер нужен как арбитр над физикой, а тут считать нечего — ход это
-- две клетки, и сервер просто прикладывает его своими же правилами.
--
-- ИГРОКИ — ДВА СТОЛБЦА p0/p1, как в бильярде и морском бое, а не массив, как в
-- дураке: в шашки играют строго вдвоём, и массив из двух элементов означал бы
-- «когда-нибудь тут будет четверо», чего не будет.
--
-- Партия — ОДНА СТРОКА, а не журнал ходов: опрашивают «не сходил ли соперник»
-- раз в полторы секунды, и проигрывать партию заново на каждый опрос было бы
-- разорительно. В state лежит текущая позиция целиком.
--
-- Партий с ботом здесь нет вовсе: они целиком в браузере и в таблицу очков не
-- идут — иначе первое место занял бы не тот, кто обыгрывает людей, а тот, кто
-- набил побед по Новичку.

CREATE TABLE IF NOT EXISTS checkers_games (
  id         uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Игроки. p1 пуст, пока вызов висит в лобби и его никто не принял.
  p0         uuid        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  p1         uuid        REFERENCES users (id) ON DELETE CASCADE,
  -- Зерно: по нему решается, КОМУ ДОСТАНУТСЯ БЕЛЫЕ. Первыми ходят белые — это
  -- правило игры, а не жребий; жребием разыгрывается цвет, потому что право
  -- первого хода заметное, и отдавать его создателю вызова нечестно.
  seed       bigint      NOT NULL,
  -- open — вызов ждёт соперника, live — играют, done — доиграли.
  status     text        NOT NULL DEFAULT 'open',
  -- Позиция как её видит сервер (shared/checkers.js, serialize). Единственный
  -- источник правды: браузер её только показывает и никогда не пересчитывает.
  state      jsonb       NOT NULL,
  -- Сколько прыжков сыграно. Он же — защита от двойной отправки: ход
  -- применяется, только если клиент прислал то же число (см. routes/checkers.js).
  -- Дважды принятый прыжок здесь особенно вреден: в цепочке ход остаётся у
  -- побившего, и повтор незаметно съел бы ещё одну шашку.
  seq        int         NOT NULL DEFAULT 0,
  -- Ничья — законный исход шашек, поэтому winner здесь пуст и у ничьей, и у
  -- незаконченной партии. Различает их status.
  winner     uuid        REFERENCES users (id) ON DELETE SET NULL,
  -- Чем кончилось: wiped, blocked, resign, timeout, draw, agreed.
  reason     text        NOT NULL DEFAULT '',
  -- Предложение ничьей: место игрока (0/1), который её предложил, или NULL.
  -- Ничья по согласию — часть игры, а не капитуляция пополам: ничейных
  -- окончаний в шашках больше, чем выигранных, и доигрывать три дамки против
  -- трёх до счётчика — не партия, а ожидание.
  draw_offer int,
  created_at timestamptz NOT NULL DEFAULT now(),
  -- Когда сделан последний ход. По нему брошенная партия отдаётся тому, кто
  -- ждёт: без этого проигрывающему выгодно просто закрыть вкладку.
  moved_at   timestamptz NOT NULL DEFAULT now()
);

-- Лобби: список открытых вызовов. Их единицы, но запрос идёт на каждый опрос.
CREATE INDEX IF NOT EXISTS checkers_games_open_idx
    ON checkers_games (status, created_at) WHERE status = 'open';
-- «Мои партии» — обе стороны, поэтому индекса два.
CREATE INDEX IF NOT EXISTS checkers_games_p0_idx ON checkers_games (p0, status);
CREATE INDEX IF NOT EXISTS checkers_games_p1_idx ON checkers_games (p1, status);

CREATE TABLE IF NOT EXISTS checkers_scores (
  user_id   uuid        PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
  -- Очко за победу — как в бильярде, дураке и морском бое.
  wins      int         NOT NULL DEFAULT 0,
  -- Поражения не влияют на место, но ПОКАЗЫВАЮТСЯ: одна победа = одно очко
  -- поощряет количество, и без второго числа сыгравший сорок партий обгонял бы
  -- выигравшего восемь из десяти.
  losses    int         NOT NULL DEFAULT 0,
  -- Ничьи — третья колонка, которой нет ни у одной другой пасхалки, потому что
  -- ни в одной из них ничьей и НЕ БЫВАЕТ. Место в таблице они не двигают
  -- СОЗНАТЕЛЬНО: считать ничью половиной победы значит поощрять размен до голых
  -- дамок, а это ровно та игра, которую никто не хочет смотреть.
  draws     int         NOT NULL DEFAULT 0,
  played_at timestamptz NOT NULL DEFAULT now()
);

-- Место в таблице: сначала победы, при равенстве — у кого меньше поражений,
-- затем кто добрался раньше. Ничьи в порядке не участвуют (см. выше).
CREATE INDEX IF NOT EXISTS checkers_scores_top_idx
    ON checkers_scores (wins DESC, losses ASC, played_at ASC);
