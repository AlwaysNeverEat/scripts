-- Топ переехал с машин на ЗАПИСИ и стал месячным.
--
-- Считаем количество СДЕЛАННЫХ записей за календарный месяц (МСК): каждое
-- 1-е число топ начинается с нуля, а прошлый месяц остаётся историей — по ней
-- страница показывает «Топ в прошлом месяце» (кто был первым к концу месяца).
--
-- Почему отдельная таблица, а не count по record_ops: очередь операций — это
-- оперативный журнал, её история живёт сутки (см. 019 и cleanupOpHistory), а
-- счётчик топа должен пережить месяц. Поэтому на каждую успешно применённую
-- запись кладём сюда одну строку — и очередь можно чистить как раньше.
--
-- Одна строка = одна запись, независимо от длины: продлённая («длинная»)
-- запись в оригинале это N получасовых слотов, но для человека она одна.
-- Строки отсюда не удаляются никогда (кроме удаления самого пользователя):
-- удалил запись — очко остаётся, работа уже была сделана.
-- Продолжения (создаются с телефоном-заглушкой EXTENSION_STUB_PHONE, т.е.
-- «Продлить» поверх уже существующей записи) не засчитываются вовсе —
-- см. isExtensionCreate() в shared/crmRecords.js.

-- Кто поставил операцию в очередь. Раньше был только текстовый author —
-- по нему топ не построить (ник меняется, гости пишут что угодно).
ALTER TABLE record_ops
  ADD COLUMN IF NOT EXISTS user_id uuid REFERENCES users (id) ON DELETE SET NULL;

-- op_id намеренно БЕЗ внешнего ключа: строки record_ops удаляются через сутки,
-- а зачёт в топе должен остаться. Уникальность нужна для идемпотентности —
-- повторная отметка операции done не удвоит счётчик.
CREATE TABLE IF NOT EXISTS record_credits (
  id          bigserial   PRIMARY KEY,
  op_id       bigint      NOT NULL UNIQUE,
  user_id     uuid        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  -- Месяц считаем в МСК и храним строкой 'YYYY-MM': месяц зачёта фиксируется
  -- в момент вставки, и никакая смена таймзоны сервера его потом не сдвинет.
  month       text        NOT NULL DEFAULT to_char(now() AT TIME ZONE 'Europe/Moscow', 'YYYY-MM'),
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS record_credits_month_idx ON record_credits (month, user_id);
