-- Пасхалка «Маджонг» (пасьянс-маджонг, «черепаха»): мини-топ внутри окна игры.
--
-- Устроена как таблица пасьянса (027), и по той же причине: партия считается в
-- браузере, а серверу остаётся ОДНА строка на игрока — его рекорд. Историю
-- партий не пишем: топ показывает лучшее, а тысячи строк «разобрал за девять
-- минут» не нужны никому.
--
-- РЕКОРД ЗДЕСЬ — МИНИМУМ, А НЕ МАКСИМУМ: соревнуются временем, за которое
-- разобран стол. Отсюда те же отличия от таблиц тетриса и тройки, что у
-- пасьянса, — LEAST вместо GREATEST в upsert и ASC в индексе.
--
-- В таблицу попадают ТОЛЬКО разобранные до конца партии: у брошенной раскладки
-- времени нет — она не «медленная», она просто не доиграна, и в топ по времени
-- её не поставить ни на какое место.
--
-- Присланный результат сервер проверяет на правдоподобность (isPlausibleRun из
-- shared/mahjong.js) — это защита от мусора, а не от человека с открытой
-- консолью; таблица пасхалки такой цены и стоит.

CREATE TABLE IF NOT EXISTS mahjong_scores (
  -- Ключ — сам пользователь: строка одна, и вставка «лучшего» превращается в
  -- обычный upsert без гонок за «а вдруг уже есть».
  user_id   uuid        PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
  -- Время рекордной партии в секундах — то, чем меряется место в топе.
  seconds   int         NOT NULL,
  -- Сколько раз в рекордной партии пришлось перемешивать стол. Перемешать можно
  -- только в тупике, так что ноль в этой колонке — честная строчка в подписи.
  shuffles  int         NOT NULL DEFAULT 0,
  -- Сколько партий всего разобрано — маленькая радость в подписи «разобрано: N».
  wins      int         NOT NULL DEFAULT 1,
  -- Когда поставлен ИМЕННО рекорд (а не последняя партия): при равном времени в
  -- топе выше тот, кто добрался до него раньше.
  played_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS mahjong_scores_top_idx ON mahjong_scores (seconds, played_at);
