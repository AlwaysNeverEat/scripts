-- Пасхалка «Бильярд» (восьмёрка): партии двух игроков и таблица очков.
--
-- ЧЕМ ЭТА ПАСХАЛКА ОТЛИЧАЕТСЯ ОТ ОСТАЛЬНЫХ. У тетриса, тройки и пасьянса (025,
-- 026, 027) сервер хранит одну строку на игрока — его рекорд, а саму партию
-- целиком считает браузер: накрутка там портит только собственное место в топе.
-- Здесь игра ПАРНАЯ, и очко, приписанное себе, отнято у живого человека —
-- значит, позицию ведёт сервер. Отсюда таблица партий, которой у соседей нет.
--
-- Партия — ОДНА СТРОКА, а не журнал ударов. Список ходов пришлось бы проигрывать
-- физикой на каждый опрос «чей ход» (а опрашивают раз в полторы секунды), и
-- вместо дешёвого SELECT получился бы пересчёт всей партии. Поэтому в state
-- лежит текущая позиция, и удар применяется к ней по одному.
--
-- last_shot нужен ровно для показа: клиент соперника берёт свою позицию,
-- проигрывает этот удар и видит, КАК шары разъехались. Без него он получал бы
-- готовую расстановку и не понимал, что произошло, — а посмотреть на чужой удар
-- в бильярде и есть половина удовольствия.
--
-- Партий с ботом здесь нет вовсе: они целиком в браузере и в таблицу очков не
-- идут — иначе первое место занял бы не тот, кто обыгрывает людей, а тот, кто
-- настрелял побед по лёгкому сопернику.

CREATE TABLE IF NOT EXISTS pool_games (
  id         uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Игроки. p1 пуст, пока вызов висит в лобби и его никто не принял.
  p0         uuid        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  p1         uuid        REFERENCES users (id) ON DELETE CASCADE,
  -- Кто разбивает: 0 — это p0, 1 — p1. Разбой даёт заметное преимущество,
  -- поэтому он достаётся не создателю вызова, а жребию.
  breaker    smallint    NOT NULL DEFAULT 0,
  -- Зерно пирамиды: по нему обе стороны раскладывают ОДИН И ТОТ ЖЕ стол.
  seed       bigint      NOT NULL,
  -- open — вызов ждёт соперника, live — играют, done — доиграли.
  status     text        NOT NULL DEFAULT 'open',
  -- Позиция как её видит сервер (shared/pool.js, serialize). Единственный
  -- источник правды: браузер её только показывает.
  state      jsonb       NOT NULL,
  -- Последний удар — четыре целых числа. Соперник проигрывает его у себя.
  last_shot  jsonb,
  -- Сколько ударов сыграно. Он же — защита от двойной отправки: удар
  -- применяется, только если клиент прислал то же число (см. routes/pool.js).
  seq        int         NOT NULL DEFAULT 0,
  winner     uuid        REFERENCES users (id) ON DELETE SET NULL,
  -- Чем кончилось: eight, eight_early, eight_foul, resign, timeout.
  reason     text        NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  -- Когда сделан последний ход. По нему брошенная партия отдаётся тому, кто
  -- ждёт: без этого проигрывающему выгодно просто закрыть вкладку.
  moved_at   timestamptz NOT NULL DEFAULT now()
);

-- Лобби: список открытых вызовов. Их единицы, но запрос идёт на каждый опрос.
CREATE INDEX IF NOT EXISTS pool_games_open_idx ON pool_games (status, created_at) WHERE status = 'open';
-- «Мои партии» — обе стороны стола, поэтому индекса два.
CREATE INDEX IF NOT EXISTS pool_games_p0_idx ON pool_games (p0, status);
CREATE INDEX IF NOT EXISTS pool_games_p1_idx ON pool_games (p1, status);

CREATE TABLE IF NOT EXISTS pool_scores (
  user_id   uuid        PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
  -- Очко за победу — и всё, как договаривались.
  wins      int         NOT NULL DEFAULT 0,
  -- Поражения не влияют на место в таблице, но ПОКАЗЫВАЮТСЯ рядом. Одна победа
  -- = одно очко поощряет количество, а не игру: сыгравший сорок партий обгонит
  -- выигравшего восемь из десяти. Показанное «12 / 4» закрывает этот спор,
  -- ничего не усложняя, — а Эло в офисе только запутает.
  losses    int         NOT NULL DEFAULT 0,
  played_at timestamptz NOT NULL DEFAULT now()
);

-- Место в таблице: сначала победы, при равенстве — у кого меньше поражений,
-- затем кто добрался раньше.
CREATE INDEX IF NOT EXISTS pool_scores_top_idx ON pool_scores (wins DESC, losses ASC, played_at ASC);
