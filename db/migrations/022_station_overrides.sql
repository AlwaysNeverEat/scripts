-- Правки справочника станций и предупреждения — из интерфейса, без релиза.
--
-- Основной справочник станций живёт в коде (`shared/stationsMeta.js`): метро,
-- линия, код перевода звонка, конфигурация, высота ворот, гидростойка,
-- заправка кондиционера. Данные там редко, но меняются — ворота перевесили,
-- гидростойку поставили, станцию открыли, — и до сих пор каждая такая мелочь
-- ждала правки файла и выкатки. Эта таблица снимает ожидание: модератор
-- правит карточку станции прямо на сайте, значения ложатся сюда и
-- накатываются поверх справочника при чтении.
--
-- `patch` — ТОЛЬКО перекрытые поля (`{"height": "2.4 м"}`), а не копия
-- карточки: чего в патче нет, то берётся из справочника, и правка кода
-- продолжает работать. Список разрешённых ключей — на бэкенде
-- (`backend/src/routes/records.js`, PATCH_FIELDS); ни `short`, ни координаты
-- туда не входят: `short` — ключ этой самой таблицы, а координаты правятся
-- вместе с точкой на карте, то есть в коде.
--
-- `warning` — предупреждение по станции («заправка кондея не работает»):
-- висит на карточке станции в обзоре, в её расписании и в окне новой записи,
-- чтобы про поломку узнавали до звонка клиенту, а не после. Живёт отдельным
-- полем, а не внутри patch: это не справочная величина, а временное
-- состояние точки, и снимают его так же часто, как ставят.
--
-- `station_key` — `short` станции из справочника («Оптиков 2»), а для точки,
-- которой в справочнике ещё нет, — заголовок её колонки из /admin/record
-- целиком. Алиасы («Мурино» = «Охтинская») в справочнике делят один `short`,
-- поэтому и правка у них общая — что и требуется, станция-то одна.

CREATE TABLE IF NOT EXISTS station_overrides (
  station_key      text        PRIMARY KEY,
  patch            jsonb       NOT NULL DEFAULT '{}'::jsonb,
  warning          text        NOT NULL DEFAULT '',
  updated_at       timestamptz NOT NULL DEFAULT now(),
  updated_by       uuid        REFERENCES users (id) ON DELETE SET NULL,
  -- Имя автора хранится строкой рядом с id: аккаунт могут удалить, а знать,
  -- кто повесил предупреждение, нужно и после этого.
  updated_by_name  text        NOT NULL DEFAULT ''
);
