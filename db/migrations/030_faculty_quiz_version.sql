-- Версия опросника у черновика распределения.
--
-- Зачем: черновик — это карта «id вопроса → ответ». Когда опросник переписали
-- (а его уже переписывали — см. шапку backend/src/faculty/quiz.js), часть id
-- осталась прежней, а смысл вопросов под ними поменялся. Недопройденный тест
-- в этот момент превращается в тихую подставу: человек возвращается, дожимает
-- оставшиеся вопросы, и в подсчёт идут его старые ответы, пришитые к новым
-- утверждениям. Ошибку при этом не видно НИКОМУ — ни ему, ни в логах.
--
-- Поэтому черновик теперь помнит, по какой версии опросника его заполняли, и
-- при несовпадении выбрасывается целиком (backend/src/faculty/store.js).
-- Версия считается от самих вопросов, руками её никто не проставляет.
--
-- Уже лежащие черновики получают пустую версию — то есть будут выброшены при
-- первом же открытии теста. Это правильно: они как раз от старого опросника.
ALTER TABLE faculty_progress
    ADD COLUMN IF NOT EXISTS quiz_version text NOT NULL DEFAULT '';
