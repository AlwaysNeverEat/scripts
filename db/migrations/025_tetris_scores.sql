-- Пасхалка «Тетрис»: мини-топ внутри окна игры.
--
-- Хранится РОВНО ОДНА строка на игрока — его лучший результат. Историю партий
-- не пишем сознательно: топ показывает рекорд, а «сколько было партий по 300
-- очков» не нужно ни игроку, ни таблице, зато это тысячи строк в месяц на
-- пасхалке. Понадобится история — она добавится отдельной таблицей, а этой не
-- помешает.
--
-- Остальные пасхалки (вордле, контекстно, сапёр) в базе не хранят ничего, и это
-- намеренно: у них результат — событие одного дня. Тетрис отличается тем, что
-- мини-топ — часть самой игры, а рекорд без хранения не переживёт и вкладку.
--
-- Партия считается в браузере (см. shared/tetris.js), поэтому сервер проверяет
-- присланный результат на правдоподобность — это защита от мусора, а не от
-- человека с открытой консолью; таблица пасхалки такой цены и стоит.

CREATE TABLE IF NOT EXISTS tetris_scores (
  -- Ключ — сам пользователь: строка одна, и вставка «лучшего» превращается в
  -- обычный upsert без гонок за «а вдруг уже есть».
  user_id   uuid        PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
  score     int         NOT NULL,
  lines     int         NOT NULL DEFAULT 0,
  level     int         NOT NULL DEFAULT 1,
  seconds   int         NOT NULL DEFAULT 0,
  -- Сколько партий доиграно до конца — маленькая радость в подписи «партий: N».
  games     int         NOT NULL DEFAULT 1,
  -- Когда поставлен ИМЕННО рекорд (а не последняя партия): при равном счёте в
  -- топе выше тот, кто добрался до него раньше.
  played_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS tetris_scores_top_idx ON tetris_scores (score DESC, played_at);
