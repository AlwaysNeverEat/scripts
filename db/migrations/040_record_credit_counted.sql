-- Запись мастера: сделана через сайт, автор известен, но очка не даёт.
--
-- Мастер на станции звонит и диктует клиента своими словами, а телефон
-- называет клиентский — от обычной записи такую не отличить ничем, кроме как
-- со слов того, кто её заводит. Поэтому в окне создания появился переключатель
-- «запись мастера», и он выключает ЗАЧЁТ, а не саму запись.
--
-- Отсюда и колонка: до неё строка record_credits существовала только у
-- зачтённой записи (одна строка = одно очко), и «не считать» означало не
-- писать строку вовсе. Но тогда пропадал бы и АВТОР — на доске такая запись
-- выглядела бы сделанной мимо сайта, а это ровно та непрозрачность, ради
-- борьбы с которой затевалась миграция 039. Теперь строка пишется всегда, а
-- counted говорит, идёт ли она в топ; skip_reason — почему нет.
--
-- Считающие запросы (routes/top.js, records/activity.js) фильтруют по counted,
-- показывающие (окно дня, авторы на доске) — нет.
--
-- Причины в skip_reason (см. creditSkipReason в backend/src/records/credits.js):
--   'by_master'  — переключатель в окне создания;
--   'junk_phone' — номер из одной и той же цифры (+7 111 111-11-11 и подобные).
-- Продолжения продлённой записи, чужие операции (перенос, правка, удаление) и
-- записи гостя строки не создают вовсе: там нет ни новой записи, ни автора.
--
-- Уже существующие строки — зачтённые: DEFAULT true меняет смысл только для
-- новых, и топ от этой миграции не шелохнётся.

ALTER TABLE record_credits
  ADD COLUMN IF NOT EXISTS counted     boolean NOT NULL DEFAULT true,
  ADD COLUMN IF NOT EXISTS skip_reason text    NOT NULL DEFAULT '';
