-- Распределение по факультетам: тест проходится ОДИН раз в жизни аккаунта,
-- результат закрепляется навсегда.
--
-- Поэтому таблиц две, и они устроены по-разному:
--
--   faculty_progress — черновик. Живёт, пока человек отвечает, и удаляется в
--     тот момент, когда результат посчитан. Нужен ровно за тем, что тест
--     проходят на работе: посреди вопросов звонит клиент, вкладку сворачивают,
--     телефон перезагружается — вернуться нужно на тот же вопрос. Прогресс
--     лежит на СЕРВЕРЕ, а не в localStorage, потому что продолжить человек
--     может с другого устройства, а чистка браузера не должна стоить ему
--     половины теста.
--
--   faculty_results — результат. Одна строка на аккаунт, и переписать её
--     нечем: в коде нет ни UPDATE, ни DELETE по этой таблице, вставка идёт
--     через ON CONFLICT DO NOTHING. Факультет — не настройка профиля, которую
--     перебирают, пока не выпадет красивая; если он меняется по желанию, он
--     ничего не значит.
--
-- Ответы сохраняем вместе с результатом (answers) — не ради статистики, а
-- потому что подсчёт живёт в коде (backend/src/faculty/quiz.js): если в
-- формулировке вопроса найдётся ошибка и веса поправят, по сохранённым ответам
-- можно будет пересчитать уже выданные факультеты, не заставляя людей проходить
-- тест заново (чего им и нельзя).

-- Факультет хранится строкой-идентификатором ('spark', 'compass', …), см.
-- shared/faculties.js. CHECK на список сознательно НЕ ставим: новый факультет
-- тогда требовал бы миграции базы, а живёт он в коде — и неизвестный
-- идентификатор фронт покажет нейтральной плашкой, а не сломается.
CREATE TABLE IF NOT EXISTS faculty_results (
  user_id   uuid        PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
  faculty   text        NOT NULL,
  -- Итоговые координаты по осям: {"tempo": -34, "system": 61, …}. Человеку не
  -- показываются (тест не должен превращаться в «подкрути ползунки»), нужны
  -- для пересчёта и разбора спорных случаев.
  scores    jsonb       NOT NULL DEFAULT '{}'::jsonb,
  answers   jsonb       NOT NULL DEFAULT '{}'::jsonb,
  taken_at  timestamptz NOT NULL DEFAULT now()
);

-- Список «кто на каком факультете» открывается на каждой странице топа и в
-- каждом профиле — индекс по факультету пригодится счётчикам вида «нас 12».
CREATE INDEX IF NOT EXISTS faculty_results_faculty_idx ON faculty_results (faculty);

CREATE TABLE IF NOT EXISTS faculty_progress (
  user_id     uuid        PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
  -- {"a1": "start", "d3": 3, "c2": ["mess", "rush", …]} — по одному ключу на
  -- отвеченный вопрос. Формат ответа зависит от типа вопроса, проверяет его
  -- backend/src/faculty/quiz.js, а не база: правила там же, где вопросы.
  answers     jsonb       NOT NULL DEFAULT '{}'::jsonb,
  started_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);
