-- ─────────────────────────────────────────────────────────────────────────────
-- Убираем oil_overrides.exclude — список «какие масла НЕ предлагать этой машине».
--
-- Он задавался стеной галочек по всему каталогу магазина в форме правки: чтобы
-- убрать одно масло, человек видел три десятка чекбоксов, не связанных с тем
-- местом, где масло реально предлагается. На выбор и так влияют допуска, цена и
-- наличие на станции, а этот фильтр молча прятал подходящее масло — причём
-- узнать, что оно спрятано, из калькулятора было нельзя.
--
-- Ключ 'pin' (закреплённое масло) остаётся и продолжает работать.
-- Миграция идемпотентна: второй прогон уже ничего не находит.
-- ─────────────────────────────────────────────────────────────────────────────

UPDATE cars
   SET oil_overrides = oil_overrides - 'exclude'
 WHERE oil_overrides ? 'exclude';
