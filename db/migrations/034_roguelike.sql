-- Пасхалка «Рогалик» (карточный забег): мини-топ внутри окна игры.
--
-- Устроена как таблицы тетриса, тройки и пасьянса (025–027), и по той же
-- причине: забег считается в браузере (игрок один, прятать не от кого — см.
-- шапку shared/roguelike.js), а серверу остаётся ОДНА строка на игрока — его
-- лучший забег. Историю забегов не пишем: топ показывает рекорд, а тысячи строк
-- «умер на четвёртом узле» не нужны никому.
--
-- РЕКОРД ЗДЕСЬ — ЦИКЛЫ (лупы), а не очки. Игра бесконечная: карта узлов
-- генерируется заново, враги растут, и забег кончается не потому, что кончился
-- контент, а потому что игрок умер. Число пройденных циклов — это и есть
-- «докуда дошёл», и мериться в этой игре можно только им.
--
-- Второй колонкой сравнения идут УЗЛЫ (floor): циклы — грубая мера, и два
-- забега «по два цикла» отличаются тем, где именно каждый умер на третьем.
-- Отсюда и составной индекс, и порядок в ORDER BY.
--
-- Присланный результат сервер проверяет на правдоподобность (isPlausibleRun из
-- shared/roguelike.js) — защита от мусора, а не от человека с открытой
-- консолью; таблица пасхалки такой цены и стоит.

CREATE TABLE IF NOT EXISTS roguelike_scores (
  -- Ключ — сам пользователь: строка одна, и «записать лучшее» превращается в
  -- обычный upsert без гонок за «а вдруг уже есть».
  user_id    uuid        PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
  -- Пройденных циклов и пройденных узлов в рекордном забеге. Место в топе
  -- считается по паре (loops, floor) — см. шапку.
  loops      int         NOT NULL,
  floor      int         NOT NULL DEFAULT 0,
  -- Из чего забег состоял: убитых врагов, из них элит и боссов.
  kills      int         NOT NULL DEFAULT 0,
  elites     int         NOT NULL DEFAULT 0,
  bosses     int         NOT NULL DEFAULT 0,
  -- Во что превратилась колода: сколько карт и до какого уровня докачана лучшая.
  -- Две оси роста забега (ширина колоды и глубина карты), и обе видны в подписи
  -- строки топа — иначе «три цикла» ничего не говорит о том, КАК их прошли.
  cards      int         NOT NULL DEFAULT 0,
  best_level int         NOT NULL DEFAULT 1,
  -- Сколько стаков мутаций накопилось за забег. Осколки редкие, и «пять мутаций
  -- за забег» — это отдельный повод для хвастовства.
  mutations  int         NOT NULL DEFAULT 0,
  seconds    int         NOT NULL DEFAULT 0,
  -- Сколько забегов доиграно до смерти — маленькая радость в подписи «забегов: N».
  runs       int         NOT NULL DEFAULT 1,
  -- Когда поставлен ИМЕННО рекорд (а не последний забег): при равном результате
  -- в топе выше тот, кто добрался до него раньше.
  played_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS roguelike_scores_top_idx
    ON roguelike_scores (loops DESC, floor DESC, played_at);
