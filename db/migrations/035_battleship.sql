-- Пасхалка «Морской бой»: партии двух игроков и таблица очков.
--
-- ЧЕМ ЭТА ПАСХАЛКА ОТЛИЧАЕТСЯ ОТ СОСЕДЕЙ. У тетриса, тройки, пасьянса и
-- рогалика (025–027, 034) сервер хранит одну строку на игрока — его рекорд, а
-- партию считает браузер: накрутка там портит только собственное место в топе.
-- У бильярда (028) партию ведёт сервер, но позицию всё равно знают оба — стол на
-- виду. Здесь ни то, ни другое, и причина та же, что у дурака (033): ЗАКРЫТАЯ
-- ИНФОРМАЦИЯ. Только в дураке закрыта чужая рука, а тут — чужая расстановка,
-- то есть ВСЯ игра целиком. Браузер, которому её отдали, не «может смухлевать»,
-- он уже выиграл. Поэтому позиция живёт ТОЛЬКО ЗДЕСЬ, а каждому игроку уезжает
-- его вид на неё (viewFor в shared/battleship.js).
--
-- ИГРОКИ — ДВА СТОЛБЦА p0/p1, как в бильярде, а не массив, как в дураке: в
-- морской бой играют строго вдвоём, и массив из двух элементов означал бы
-- «когда-нибудь тут будет четверо», чего не будет никогда.
--
-- Партия — ОДНА СТРОКА, а не журнал выстрелов: за партию их под сотню, а
-- опрашивают «не сходил ли соперник» раз в полторы секунды, и проигрывать всю
-- партию заново на каждый опрос было бы разорительно. В state лежит текущая
-- позиция целиком — оба флота и оба поля выстрелов.
--
-- РАССТАНОВКА — ЧАСТЬ ПАРТИИ, а не подготовка к ней: партия начинается в
-- статусе live с phase = 'setup' внутри state, и стрелять нельзя, пока не готовы
-- оба. Отдельного статуса под расстановку нет намеренно — «кто сейчас ходит» в
-- ней не значит ничего, а вот сдаться и бросить партию можно уже тогда.
--
-- Партий с ботом здесь нет вовсе: они целиком в браузере и в таблицу очков не
-- идут — иначе первое место занял бы не тот, кто обыгрывает людей, а тот, кто
-- настрелял побед по Юнге.

CREATE TABLE IF NOT EXISTS battleship_games (
  id         uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Игроки. p1 пуст, пока вызов висит в лобби и его никто не принял.
  p0         uuid        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  p1         uuid        REFERENCES users (id) ON DELETE CASCADE,
  -- Зерно: по нему решается, кто стреляет первым. Первый выстрел — заметное
  -- преимущество, поэтому он достаётся жребию, а не создателю вызова, и жребий
  -- бросает сервер: знать его заранее не должен никто.
  seed       bigint      NOT NULL,
  -- open — вызов ждёт соперника, live — расставляются или стреляют, done —
  -- доиграли. Расстановка живёт внутри state (см. шапку).
  status     text        NOT NULL DEFAULT 'open',
  -- Позиция как её видит сервер (shared/battleship.js, serialize). Единственный
  -- источник правды: браузер её только показывает и никогда не пересчитывает.
  state      jsonb       NOT NULL,
  -- Сколько ходов сыграно. Он же — защита от двойной отправки: ход применяется,
  -- только если клиент прислал то же число (см. routes/battleship.js). Дважды
  -- принятый выстрел здесь особенно вреден: попал — стреляй ещё, и повтор
  -- незаметно съел бы клетку из очереди соперника.
  seq        int         NOT NULL DEFAULT 0,
  winner     uuid        REFERENCES users (id) ON DELETE SET NULL,
  -- Чем кончилось: fleet, resign, timeout.
  reason     text        NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  -- Когда сделан последний ход. По нему брошенная партия отдаётся тому, кто
  -- ждёт: без этого проигрывающему выгодно просто закрыть вкладку.
  moved_at   timestamptz NOT NULL DEFAULT now()
);

-- Лобби: список открытых вызовов. Их единицы, но запрос идёт на каждый опрос.
CREATE INDEX IF NOT EXISTS battleship_games_open_idx
    ON battleship_games (status, created_at) WHERE status = 'open';
-- «Мои партии» — обе стороны, поэтому индекса два.
CREATE INDEX IF NOT EXISTS battleship_games_p0_idx ON battleship_games (p0, status);
CREATE INDEX IF NOT EXISTS battleship_games_p1_idx ON battleship_games (p1, status);

CREATE TABLE IF NOT EXISTS battleship_scores (
  user_id   uuid        PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
  -- Очко за победу — и всё, как в бильярде и дураке.
  wins      int         NOT NULL DEFAULT 0,
  -- Поражения не влияют на место в таблице, но ПОКАЗЫВАЮТСЯ рядом: одна победа
  -- = одно очко поощряет количество, и без второго числа сыгравший сорок партий
  -- обгонял бы выигравшего восемь из десяти.
  losses    int         NOT NULL DEFAULT 0,
  played_at timestamptz NOT NULL DEFAULT now()
);

-- Место в таблице: сначала победы, при равенстве — у кого меньше поражений,
-- затем кто добрался раньше.
CREATE INDEX IF NOT EXISTS battleship_scores_top_idx
    ON battleship_scores (wins DESC, losses ASC, played_at ASC);
