-- Скины: оформление, которое человек носит на себе и которое видят все
-- (рамка аватара, баннер лидов, картинка на капсулах записей) — см.
-- shared/skins.js.
--
-- ОДНА СТРОКА НА ЧЕЛОВЕКА: скин — это его текущий выбор, а не история
-- выборов. Скин собирается ПО ЧАСТЯМ из разных паков, поэтому parts — словарь
-- «часть → пак» ({"frame": "cat", "leads": null}), а не один пак на всё.
-- Снятый скин — строка с пустыми частями, а не удалённая: код оператора
-- рядом остаётся и пригодится при следующем надевании.
--
-- operator — код оператора из вкладки «Лиды» (там он живёт на устройстве).
-- Здесь он нужен ВСЕМ остальным: карточку звонка открывает другой человек, и
-- узнать, чей это звонок и в чьём скине его показать, ему больше неоткуда.

CREATE TABLE IF NOT EXISTS user_skins (
  user_id    uuid        PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
  parts      jsonb       NOT NULL DEFAULT '{}'::jsonb,
  operator   text        NOT NULL DEFAULT '',
  updated_at timestamptz NOT NULL DEFAULT now()
);
