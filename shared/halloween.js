// С 1 октября по 2 ноября включительно — по местному календарю браузера.
export function isHalloweenSeason(date = new Date()) {
    const m = date.getMonth();
    return m === 9 || (m === 10 && date.getDate() <= 2);
}

// Следующая фраза: случайная, но не та же, что только что. Повтор подряд
// читается как «сломался», а не как «повторил шутку».
export function pickPhrase(prev = null, rnd = Math.random, phrases = PHRASES) {
    if (phrases.length < 2) return phrases[0] ?? '';
    let i = Math.floor(rnd() * phrases.length) % phrases.length;
    if (phrases[i] === prev) i = (i + 1) % phrases.length;
    return phrases[i];
}
