// С 1 октября по 2 ноября включительно — по местному календарю браузера.
export function isHalloweenSeason(date = new Date()) {
    const m = date.getMonth();
    return m === 9 || (m === 10 && date.getDate() <= 2);
}

// Фразы идут КОЛОДОЙ: перемешали, выдали все по одной, перемешали снова.
// Простой случайный выбор из трёх сотен повторяет фразу уже через пару
// десятков реплик (парадокс дней рождения), а паучок говорит раз в полторы
// минуты — к обеду он «заело». Колодой повтор случится не раньше, чем
// прозвучат все. Стык двух колод проверяется отдельно: последняя фраза старой
// не должна стать первой новой — повтор подряд читается как «сломался».
export function phraseDeck(rnd = Math.random, phrases = PHRASES) {
    let deck = [];
    let last = null;
    return function next() {
        if (!phrases.length) return '';
        if (!deck.length) {
            deck = phrases.slice();
            for (let i = deck.length - 1; i > 0; i--) {
                const j = Math.floor(rnd() * (i + 1)) % (i + 1);
                [deck[i], deck[j]] = [deck[j], deck[i]];
            }
            // Выдаём с конца — значит, «первая новой» лежит в конце.
            if (deck.length > 1 && deck[deck.length - 1] === last) {
                [deck[0], deck[deck.length - 1]] = [deck[deck.length - 1], deck[0]];
            }
        }
        last = deck.pop();
        return last;
    };
}
