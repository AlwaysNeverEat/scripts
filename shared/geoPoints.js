// ─────────────────────────────────────────────────────────────────────────────
// Точки для пасхалки «Гео»: откуда берётся место, которое надо угадать.
//
// ПОЧЕМУ СПИСОК, А НЕ СЛУЧАЙНАЯ ТОЧКА ПЛАНЕТЫ. Снимки улиц есть на считаных
// процентах суши, а суша — это треть шара: случайная координата почти всегда
// попадает туда, где смотреть нечего, и сервер уходит в длинный перебор.
// Поэтому здесь опорные точки — города стран, где покрытие точно есть, а
// разнообразие даёт РАЗБРОС вокруг них (см. ниже).
//
// Список подобран под покрытие MAPILLARY, а оно рванее гугловского: снимки
// краудсорсинговые, и плотность идёт от того, сколько в стране энтузиастов, а
// не от маршрутов съёмочных машин. Европа, Штаты и Япония покрыты густо, дальше
// местами. Страны, где рассчитывать не на что, сюда просто не попали — а точка,
// рядом с которой ничего не нашлось, пропускается сервером.
//
// Список специально широкий по странам, а не по городам: игра, в которой
// половина точек — Штаты, вырождается в «угадай штат». Одна страна — от одной
// до десяти опорных точек, по размеру и по тому, сколько в ней покрыто.
//
// Разброс (jitter) — до JITTER_KM от опорной точки. Он нужен, чтобы одна и та
// же точка не выпадала дважды: с ним у каждой опоры бесконечно много вариантов,
// и запоминать «а, это тот перекрёсток в Осло» бесполезно.
//
// Радиус небольшой, и на то две причины. Первая: Mapillary не принимает запрос
// с квадратом больше 0.010 кв. градуса (около 11 км в поперечнике), поэтому
// сервер и так смотрит недалеко вокруг — уехав на двадцать километров, он
// заглядывал бы в поле рядом с единственной снятой улицей. Вторая: опоры стоят
// не у границ, и на таком расстоянии подпись страны остаётся верной — а её
// показывают в конце раунда.
//
// Реального места здесь всё равно нет: сервер берёт эту координату лишь как
// ЗАПРОС в банк снимков Mapillary и получает настоящую точку съёмки
// (backend/src/geo/panoramas.js). Если рядом ничего не нашлось — берётся
// следующая точка. Поэтому список не обязан быть точным до улицы.
// ─────────────────────────────────────────────────────────────────────────────

