/** Опорные точки как объекты. */
export const POINTS = P.map(([lat, lng, label]) => ({ lat, lng, label }));

// Сколько стран в списке — показываем в окне игры, чтобы было видно масштаб.
export const COUNTRIES = new Set(POINTS.map(p => p.label)).size;

const KM_PER_DEG = 111.32;

/**
 * Опорная точка со случайным сдвигом.
 *
 * rand — источник случайности: () => [0,1). Он передаётся снаружи, потому что у
 * дейли он ДЕТЕРМИНИРОВАННЫЙ (хэш от аккаунта и даты), а у соло с дуэлью —
 * обычный Math.random.
 *
 * Сдвиг берём равномерно по кругу (корень из случайного числа для радиуса),
 * иначе точки кучкуются в центре и разброс почти не работает.
 */
export function pickPoint(rand = Math.random) {
    const base = POINTS[Math.floor(rand() * POINTS.length) % POINTS.length];
    const dist = JITTER_KM * Math.sqrt(rand());
    const angle = 2 * Math.PI * rand();
    const dLat = (dist * Math.cos(angle)) / KM_PER_DEG;
    // Ближе к полюсам градус долготы короче — без косинуса разброс на широте
    // Тромсё получился бы вчетверо шире, чем в Найроби.
    const cos = Math.max(0.05, Math.cos((base.lat * Math.PI) / 180));
    const dLng = (dist * Math.sin(angle)) / (KM_PER_DEG * cos);
    return {
        lat: Math.max(-85, Math.min(85, base.lat + dLat)),
        lng: ((base.lng + dLng + 540) % 360) - 180,
        label: base.label,
    };
}
