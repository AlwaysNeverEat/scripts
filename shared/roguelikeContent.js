// Пасхалка «Рогалик» — ВЕСЬ КОНТЕНТ одним файлом: карты, враги и их повадки,
// модификаторы врагов, мутации карт, события и статусы.
//
// ПОЧЕМУ КОНТЕНТ ОТДЕЛЬНО ОТ ДВИЖКА (shared/roguelike.js): движок не знает ни
// одной карты по имени. Карта — это список эффектов ([нанести 6 урона],
// [дать 5 блока]), враг — список намерений, модификатор — два-три числа. Новая
// карта добавляется СТРОЧКОЙ СЮДА, и логика при этом не трогается вовсе. Как
// только в движке появится `if (card.id === '...')`, эта затея сломана.
//
// ОБЪЁМ КОНТЕНТА ЗДЕСЬ СОЗНАТЕЛЬНО МАЛЕНЬКИЙ. Разнообразие даёт не количество
// написанного, а перемножение: пять базовых врагов × девять модификаторов ×
// эскалация циклов дают сотни ощутимо разных встреч, а двадцать семь карт ×
// уровни × десять мутаций — колоды, которые не повторяются. Писать уникального
// босса на каждую встречу — это способ выдохнуться на пятнадцатом и получить
// игру на полтора часа.
//
// ЧИСЛА ТУТ — ЭТО БАЛАНС, и трогать их поодиночке нельзя: карты подобраны под
// здоровье врагов, здоровье врагов — под три энергии в ход и руку из пяти карт.
// Проверка — shared/roguelike.test.js: там есть прогон «средний игрок против
// первого цикла», и он держит планку «первый цикл проходится, третий — нет».
//
// ЯЗЫК: тексты карт СОБИРАЕТ ДВИЖОК из эффектов (cardText в roguelike.js) — в
// описании карты нет ни одной строки текста, иначе она разъехалась бы с
// числами при первом же апгрейде.
// ─────────────────────────────────────────────────────────────────────────────

