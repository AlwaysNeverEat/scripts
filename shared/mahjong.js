// ─────────────────────────────────────────────────────────────────────────────
// Пасхалка «Маджонг» (пасьянс-маджонг, «черепаха»): правила одним файлом.
//
// Здесь ВСЁ, что знает про игру и фронт, и бэкенд: набор фишек, раскладка,
// «какая фишка свободна», что с чем сходится, раздача, перемешивание и проверка
// результата. Окно игры (frontend/src/mahjong.js) только рисует стол и слушает
// мышь, а сервер (backend/src/routes/mahjong.js) берёт отсюда проверку
// правдоподобности — иначе «а бывает ли такая партия» пришлось бы держать в
// двух местах.
//
// ПАРТИЯ СЧИТАЕТСЯ В БРАУЗЕРЕ, как в тетрисе, тройке и пасьянсе, и по той же
// причине: соперника нет, закрытой информации нет (все 144 фишки лежат лицом
// вверх с первой секунды), прятать не от кого. На сервер уходит ОДИН запрос — и
// только у РАЗОБРАННОЙ партии: топ тут по времени, а у брошенной раскладки
// времени нет. Сравните с дураком и морским боем: там партию ведёт сервер не
// «на всякий случай», а потому что браузер, знающий чужие карты или чужой флот,
// знает лишнее.
//
// РАЗДАЧА ВСЕГДА РАЗБИРАЕМАЯ, и это не мелочь. Если разложить 144 фишки
// случайно, каждая третья раскладка не разбирается вовсе — а в топе по времени
// это означало бы соревнование «кому повезло с раздачей». Поэтому стол
// собирается ЗАДОМ НАПЕРЁД: у пустой раскладки берутся два места, свободных
// ОДНОВРЕМЕННО, в них кладётся пара, места «занимаются» — и так 72 раза. Тот же
// порядок, проигранный с начала, и есть готовое решение. Тупик после этого
// остаётся возможным, но он теперь ЧЕЙ-ТО ВЫБОР, а не свойство раздачи, — и на
// этот случай есть перемешивание (см. reshuffle).
//
// Фишка — ОДНО ЧИСЛО (индекс в KINDS), а не объект: стол перебирается на каждый
// клик (проверить свободность) и на каждую подсказку, и объекты тут не дают
// ничего, кроме мусора для сборщика.
// ─────────────────────────────────────────────────────────────────────────────

// ── Фишки ────────────────────────────────────────────────────────────────────

