// Спрайт — сетка 7×6 ровно по числу видов (42 = 7×6, без пустых клеток).
export const SPRITE_COLS = 7;
export const spriteCol = kind => kind % SPRITE_COLS;
export const spriteRow = kind => (kind / SPRITE_COLS) | 0;

// Геометрия спрайта в пикселях картинки. Фишка нарисована как ЛИЦО ПЛЮС БОРТИК
// вправо и вниз (свет падает слева сверху), и это две разные величины:
//   • шаг сетки на столе — размер ЛИЦА: соседи в ряду встают вплотную и
//     закрывают бортик друг друга, видно его только у крайней фишки;
//   • размер картинки — размер КЛЕТКИ, лицо плюс тот самый бортик.
// Нужны обе и окну (frontend/src/mahjong.js), и сборщику спрайта
// (design/mahjong-tiles/prepare.mjs), поэтому лежат здесь, а не в двух местах.
export const SPRITE = { cellW: 88, cellH: 110, faceW: 78, faceH: 98, pad: 1 };

// Подписи для тултипа фишки. Мастям русские имена дают по-разному («точки» они
// же «круги», «символы» они же «иероглифы») — берём самые ходовые.
const SUIT_LABEL = ['Точки', 'Бамбук', 'Символы'];
const REST_LABEL = [
    'Ветер Востока', 'Ветер Юга', 'Ветер Запада', 'Ветер Севера',
    'Красный дракон', 'Зелёный дракон', 'Белый дракон',
    'Цветок: слива', 'Цветок: орхидея', 'Цветок: хризантема', 'Цветок: бамбук',
    'Время года: весна', 'Время года: лето', 'Время года: осень', 'Время года: зима',
];
export function tileLabel(kind) {
    if (kind < 27) return `${SUIT_LABEL[(kind / 9) | 0]} ${(kind % 9) + 1}`;
    return REST_LABEL[kind - 27];
}

// Цветы сходятся с цветами, времена года — с временами года. Это единственное
// место, где правило «одинаковые фишки» ослаблено, и без него четыре цветка
// (каждый в наборе ровно один) не разобрать вовсе.
export const FIRST_FLOWER = KINDS.indexOf('flw-plum');
export const FIRST_SEASON = KINDS.indexOf('sea-spring');

/** Группа, внутри которой фишки взаимозаменяемы: для обычных — она сама. */
export function groupOf(kind) {
    if (kind >= FIRST_SEASON) return FIRST_SEASON;
    if (kind >= FIRST_FLOWER) return FIRST_FLOWER;
    return kind;
}

/** Сходятся ли две фишки (сами фишки, без учёта того, свободны ли они). */
export const matches = (a, b) => a >= 0 && b >= 0 && groupOf(a) === groupOf(b);

// Набор классический: масти, ветры и драконы по четыре штуки, цветов и времён
// года — по одному. 34 × 4 + 4 + 4 = 144.
export const COPIES = 4;
export const TILES = 144;
export const PAIRS = TILES / 2;

/** Полный набор фишек одной партии — 144 числа, ещё не разложенных. */
export function fullSet() {
    const out = [];
    for (let k = 0; k < KINDS.length; k++) {
        const n = k >= FIRST_FLOWER ? 1 : COPIES;
        for (let i = 0; i < n; i++) out.push(k);
    }
    return out;
}

// ── Раскладка «черепаха» ─────────────────────────────────────────────────────
//
// Та самая классическая горка из 144 фишек: пять этажей, голова слева и хвост
// из двух фишек справа. Других раскладок нет сознательно — «черепаху» узнают
// все, кто когда-либо открывал маджонг, а десяток фигур пришлось бы ещё и
// выбирать перед партией, что для пасхалки лишний экран.
//
// Координаты — В ПОЛОВИНАХ ФИШКИ (фишка занимает 2×2), потому что и голова с
// хвостом, и верхняя фишка стоят СО СДВИГОМ НА ПОЛОВИНУ относительно сетки.
// Целые полушаги позволяют сравнивать места точным `===`, а не возиться с
// дробями там, где от них зависит, свободна фишка или нет.
export const UNIT = 2;

// Ряды нижнего этажа: [ряд, первый столбец, последний столбец]. 84 фишки, плюс
// голова и хвост по бокам — 87.
const FLOOR_ROWS = [
    [0, 1, 12], [1, 3, 10], [2, 2, 11], [3, 1, 12],
    [4, 1, 12], [5, 2, 11], [6, 3, 10], [7, 1, 12],
];

function buildLayout() {
    const out = [];
    const put = (x, y, z) => out.push({ x, y, z });

    for (const [row, from, to] of FLOOR_ROWS) {
        for (let col = from; col <= to; col++) put(col * UNIT, row * UNIT, 0);
    }
    // Голова слева и хвост справа стоят посередине высоты — между третьим и
    // четвёртым рядом, то есть на полшага ниже сетки.
    put(0, 7, 0);
    put(13 * UNIT, 7, 0);
    put(14 * UNIT, 7, 0);

    // Этажи выше — вложенные прямоугольники по центру спины: 6×6, 4×4, 2×2.
    for (const [z, x0, x1, y0, y1] of [[1, 4, 9, 1, 6], [2, 5, 8, 2, 5], [3, 6, 7, 3, 4]]) {
        for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) put(x * UNIT, y * UNIT, z);
    }
    // Верхняя фишка лежит ровно на стыке четырёх нижних — снова полшага.
    put(13, 7, 4);

    return Object.freeze(out.map(Object.freeze));
}

export const LAYOUT = buildLayout();

// Габариты стола в полушагах — нужны окну, чтобы посчитать размер фишки под
// ширину экрана. Считаются из самой раскладки: руками их задать значит
// однажды разойтись с ней.
export const BOARD_W = Math.max(...LAYOUT.map(p => p.x)) + UNIT;
export const BOARD_H = Math.max(...LAYOUT.map(p => p.y)) + UNIT;
export const LAYERS = Math.max(...LAYOUT.map(p => p.z)) + 1;

// Кто кого закрывает и кто кому сосед — считается один раз на всю игру: сама
// раскладка не меняется, меняется только то, какие места ещё заняты.
//
// `above` — места ЛЮБОГО верхнего этажа, накрывающие это (в «черепахе» хватило
// бы и одного этажа вверх, но проверять все дешевле, чем однажды нарисовать
// раскладку, где второй этаж висит над пустотой).
// `left`/`right` — соседи того же этажа, прижатые сбоку.
const NEIGHBOURS = LAYOUT.map((p, i) => {
    const above = [], left = [], right = [];
    LAYOUT.forEach((q, j) => {
        if (i === j) return;
        const dy = Math.abs(q.y - p.y);
        if (dy >= UNIT) return;                       // разные ряды — не мешают
        if (q.z > p.z && Math.abs(q.x - p.x) < UNIT) above.push(j);
        if (q.z !== p.z) return;
        // Сосед считается прижатым, если он занимает соседнюю колонку хотя бы
        // частью: у головы и хвоста сдвиг на полшага, и «ровно рядом» их бы не
        // поймало.
        const dx = q.x - p.x;
        if (dx > 0 && dx < 2 * UNIT) right.push(j);
        if (dx < 0 && dx > -2 * UNIT) left.push(j);
    });
    return { above, left, right };
});

// ── Партия ───────────────────────────────────────────────────────────────────

// Генератор с зерном (mulberry32) — как в тетрисе, тройке и пасьянсе: нужен не
// ради «честности», а ради тестов, в которых раздачу надо повторить фишка в
// фишку.
function makeRng(seed) {
    let a = seed >>> 0;
    return () => {
        a = (a + 0x6d2b79f5) >>> 0;
        let t = a;
        t = Math.imul(t ^ (t >>> 15), t | 1);
        t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
        return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
}

const shuffled = (arr, rng) => {
    const a = arr.slice();
    for (let i = a.length - 1; i > 0; i--) {
        const j = Math.floor(rng() * (i + 1));
        [a[i], a[j]] = [a[j], a[i]];
    }
    return a;
};

/**
 * Разбить набор фишек на пары. Внутри группы (цветы, времена года) фишки
 * взаимозаменяемы, поэтому пары собираются ПО ГРУППАМ: иначе к двум цветкам
 * мог бы не найтись второй такой же, хотя разобрать их можно.
 */
function toPairs(tiles) {
    const byGroup = new Map();
    for (const k of tiles) {
        const g = groupOf(k);
        if (!byGroup.has(g)) byGroup.set(g, []);
        byGroup.get(g).push(k);
    }
    const pairs = [];
    for (const list of byGroup.values()) {
        for (let i = 0; i + 1 < list.length; i += 2) pairs.push([list[i], list[i + 1]]);
    }
    return pairs;
}

/**
 * Разложить пары по местам ЗАДОМ НАПЕРЁД: на каждом шаге берутся два места,
 * свободных ОДНОВРЕМЕННО, — тогда тот же порядок, сыгранный с начала, окажется
 * готовым решением.
 *
 * Оба места берутся из ОДНОГО списка свободных, а не «первое, убрали, посчитали
 * заново, второе»: во втором случае вторая фишка могла быть закрыта первой, и
 * такой ход в настоящей партии сделать нельзя — раздача перестала бы быть
 * разбираемой.
 *
 * Возвращает и сам стол (массив длиной LAYOUT.length: вид фишки на каждом
 * месте), и ПОРЯДОК, которым его собирали. Порядок — это готовое решение, и
 * держим мы его не для игрока (подсказку честно считает findMove, а решения
 * окно не показывает вовсе), а потому что иначе обещание «раздача всегда
 * разбираема» нечем ни проверить тестом, ни предъявить.
 */
function dealInto(slots, pairs, rng) {
    const tiles = new Array(LAYOUT.length).fill(-1);
    const busy = new Set(slots);
    const solution = [];

    for (const [a, b] of shuffled(pairs, rng)) {
        const free = [...busy].filter(i => freeIn(busy, i));
        if (free.length < 2) return null;    // на «черепахе» не случается
        const i = free[Math.floor(rng() * free.length)];
        let j = i;
        while (j === i) j = free[Math.floor(rng() * free.length)];
        tiles[i] = a;
        tiles[j] = b;
        busy.delete(i);
        busy.delete(j);
        solution.push([i, j]);
    }
    return { tiles, solution };
}

/**
 * Разложить с повторами: примерно каждая пятнадцатая попытка упирается в
 * тупик — под конец в `busy` остаётся стопка (нижнее место закрыто верхним), и
 * свободного места остаётся ОДНО, а нужно два. Разгребать такой хвост
 * перестановками сложнее, чем начать раскладку заново: попытка стоит доли
 * миллисекунды, а шанс, что подряд не повезёт сорок раз, — одна триллионная.
 */
function deal(slots, pairs, rng) {
    for (let attempt = 0; attempt < 40; attempt++) {
        const done = dealInto(slots, pairs, rng);
        if (done) return done;
    }
    throw new Error('маджонг: не удалось разложить разбираемый стол');
}

/** Свободно ли место `i`, если заняты ровно места из `busy`. */
function freeIn(busy, i) {
    const n = NEIGHBOURS[i];
    if (n.above.some(j => busy.has(j))) return false;
    return !n.left.some(j => busy.has(j)) || !n.right.some(j => busy.has(j));
}

/**
 * Новая партия. seed — зерно случайности (по умолчанию своё на каждую).
 *
 * Стол — массив по местам раскладки: вид фишки или −1, если место уже разобрано.
 * Отдельного списка «что где лежит» нет: место и есть индекс.
 */
export function createGame({ seed } = {}) {
    const s = seed == null ? (Math.random() * 0xffffffff) >>> 0 : seed;
    const rng = makeRng(s);
    const slots = LAYOUT.map((_, i) => i);
    const { tiles, solution } = deal(slots, toPairs(fullSet()), rng);

    return {
        seed: s,
        rng,
        tiles,
        solution,           // порядок сборки = готовое решение (см. dealInto)
        left: TILES,        // сколько фишек ещё на столе
        pairs: 0,           // сколько пар уже разобрано
        shuffles: 0,        // сколько раз пришлось перемешивать
        elapsedMs: 0,
        won: false,
    };
}

/** Свободна ли фишка на месте `i`: не накрыта сверху и открыта слева или справа. */
export function isFree(game, i) {
    if (game.tiles[i] < 0) return false;
    const n = NEIGHBOURS[i];
    if (n.above.some(j => game.tiles[j] >= 0)) return false;
    return !n.left.some(j => game.tiles[j] >= 0) || !n.right.some(j => game.tiles[j] >= 0);
}

/** Все свободные места — окну для подсветки, боту из теста для хода. */
export function freeTiles(game) {
    const out = [];
    for (let i = 0; i < game.tiles.length; i++) if (isFree(game, i)) out.push(i);
    return out;
}

/** Можно ли снять эту пару: обе на столе, обе свободны, виды сходятся. */
export function canTake(game, a, b) {
    return a !== b && isFree(game, a) && isFree(game, b) && matches(game.tiles[a], game.tiles[b]);
}

/** Снять пару. Возвращает true, если ход был законным (и сделан). */
export function take(game, a, b) {
    if (game.won || !canTake(game, a, b)) return false;
    game.tiles[a] = -1;
    game.tiles[b] = -1;
    game.left -= 2;
    game.pairs += 1;
    if (!game.left) game.won = true;
    return true;
}

/**
 * Первая пара, которую можно снять, — для подсказки и для «есть ли ходы».
 *
 * Перебор идёт строго по номерам мест, поэтому на одном и том же столе ответ
 * ВСЕГДА ОДИН И ТОТ ЖЕ: подсказка не должна прыгать по столу от того, что игрок
 * подождал ещё секунду (то же правило, что у findMove в тройке).
 */
export function findMove(game) {
    const free = freeTiles(game);
    for (let i = 0; i < free.length; i++) {
        for (let j = i + 1; j < free.length; j++) {
            if (matches(game.tiles[free[i]], game.tiles[free[j]])) return [free[i], free[j]];
        }
    }
    return null;
}

export const hasMove = game => findMove(game) !== null;

/**
 * Перемешать оставшиеся фишки. Возвращает true, если перемешали.
 *
 * Раскладывается заново ТЕМ ЖЕ способом, что и партия, — значит после
 * перемешивания стол снова гарантированно разбирается. Иначе кнопка «нет ходов»
 * могла бы выдать второй тупик подряд, и партию оставалось бы только бросить.
 *
 * Счётчик перемешиваний уезжает в топ рядом со временем: секундомер во время
 * тупика идёт, так что перемешивание и без того наказано, а в подписи рекорда
 * «ни разу не перемешивал» — честная строчка.
 */
export function reshuffle(game) {
    if (game.won || game.left < 2) return false;
    const slots = [];
    const rest = [];
    for (let i = 0; i < game.tiles.length; i++) {
        if (game.tiles[i] < 0) continue;
        slots.push(i);
        rest.push(game.tiles[i]);
    }
    const dealt = deal(slots, toPairs(rest), game.rng);
    game.tiles = dealt.tiles;
    game.solution = dealt.solution;
    game.shuffles += 1;
    return true;
}

/** Секундомер. Идёт только пока играют — окно само решает, когда звать. */
export function tick(game, ms) {
    if (!game.won) game.elapsedMs += ms;
}

