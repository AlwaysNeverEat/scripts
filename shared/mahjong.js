/**
 * Похоже ли на настоящую разобранную партию.
 *
 * Проверка ГРУБАЯ и такой задумана: это защита от мусора, а не от человека с
 * открытой консолью — мини-топ пасхалки большего не стоит (та же цена, что у
 * тетриса, тройки и пасьянса).
 */
export function isPlausibleRun({ seconds, shuffles }) {
    const sec = Number(seconds);
    const sh = Number(shuffles);
    const all = [sec, sh];

    if (!all.every(v => Number.isFinite(v) && v >= 0)) return { ok: false, reason: 'shape' };
    if (!all.every(Number.isInteger)) return { ok: false, reason: 'shape' };
    if (sec < MIN_SECONDS) return { ok: false, reason: 'too_fast' };
    if (sec > MAX_SECONDS) return { ok: false, reason: 'too_long' };
    if (sh > MAX_SHUFFLES) return { ok: false, reason: 'too_many_shuffles' };
    return { ok: true };
}
