const AVATAR_BY_ID = new Map(AVATAR_FX.map(f => [f.id, f]));
const PROFILE_BY_ID = new Map(PROFILE_FX.map(f => [f.id, f]));

export function avatarFxById(id) { return AVATAR_BY_ID.get(id) || null; }
export function profileFxById(id) { return PROFILE_BY_ID.get(id) || null; }

// Приведение пары из базы/запроса к валидной: незнакомый id (сняли эффект из
// каталога, а у человека записан старый) молча превращается в «без эффекта» —
// профиль из-за него ломаться не должен.
export function normalizeFx(fx) {
    return {
        avatar: avatarFxById(fx?.avatar)?.id || null,
        profile: profileFxById(fx?.profile)?.id || null,
    };
}
