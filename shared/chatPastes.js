// ─────────────────────────────────────────────────────────────────────────────
// Пасты во вкладке «Чаты» — заготовленные ответы клиентам, разложенные по
// темам. Здесь правила, общие для сервера и окна: что такое правильная паста,
// как пишется тема и стартовый набор, который человек получает «из коробки».
//
// Хранение — backend/src/chat/pastes.js, окно — frontend/src/chatPastes.js.
//
// ТЕМ У ПАСТЫ МОЖЕТ БЫТЬ НЕСКОЛЬКО, и тема — это короткая метка, а не
// заголовок: она рисуется таблеткой в фильтре над списком и на каждой
// карточке. Отсюда потолки — длина темы и число тем у пасты: таблетка на
// полэкрана выталкивает из фильтра все остальные, а карточка с семью темами
// перестаёт читаться как ответ клиенту.
// ─────────────────────────────────────────────────────────────────────────────

export const TOPIC_MAX = 24;   // знаков в теме
export const TOPICS_MAX = 4;   // тем у одной пасты
export const TITLE_MAX = 60;
export const BODY_MAX = 4000;  // столько же принимает ответ в CRM
export const PASTES_MAX = 300; // паст у одного человека

// Тема: без лишних пробелов и не длиннее таблетки.
export function cleanTopic(raw) {
    return String(raw ?? '').replace(/\s+/g, ' ').trim().slice(0, TOPIC_MAX).trim();
}

const topicKey = (t) => cleanTopic(t).toLocaleLowerCase('ru');

// Тема, набранная руками, пишется так же, как уже существующая: «запись» и
// «Запись» — одна тема, и в фильтре не должно появиться двух таблеток.
export function canonTopic(raw, existing = []) {
    const t = cleanTopic(raw);
    if (!t) return '';
    const k = topicKey(t);
    return existing.find(e => topicKey(e) === k) || t;
}

// Темы пасты: чистые, без повторов (без учёта регистра), не больше потолка.
export function cleanTopics(list, existing = []) {
    const out = [];
    for (const raw of Array.isArray(list) ? list : []) {
        const t = canonTopic(raw, existing);
        if (t && !out.some(o => topicKey(o) === topicKey(t))) out.push(t);
        if (out.length >= TOPICS_MAX) break;
    }
    return out;
}

/**
 * Проверить и почистить пасту перед сохранением.
 * @returns {{ paste: { title, body, topics } } | { error: string }}
 */
export function cleanPaste(raw, existingTopics = []) {
    const body = String(raw?.body ?? '').replace(/\r\n?/g, '\n').trim();
    if (!body) return { error: 'пустой текст пасты' };
    if (body.length > BODY_MAX) return { error: `текст длиннее ${BODY_MAX} знаков` };
    const title = String(raw?.title ?? '').replace(/\s+/g, ' ').trim().slice(0, TITLE_MAX);
    return { paste: { title, body, topics: cleanTopics(raw?.topics, existingTopics) } };
}

// Все темы по порядку первого появления в списке: стартовый набор идёт от
// сбора данных к закрытию диалога, и фильтр повторяет ход разговора, а не
// алфавит.
export function topicsOf(pastes) {
    const out = [];
    for (const p of pastes || []) {
        for (const t of p.topics || []) if (!out.some(o => topicKey(o) === topicKey(t))) out.push(t);
    }
    return out;
}

// Отбор по теме ('' — все) и по строке поиска (заголовок, текст, темы).
export function filterPastes(pastes, { topic = '', q = '' } = {}) {
    const tk = topic ? topicKey(topic) : '';
    const words = String(q).toLocaleLowerCase('ru').split(/\s+/).filter(Boolean);
    return (pastes || []).filter(p => {
        if (tk && !(p.topics || []).some(t => topicKey(t) === tk)) return false;
        if (!words.length) return true;
        const hay = `${p.title} ${p.body} ${(p.topics || []).join(' ')}`.toLocaleLowerCase('ru');
        return words.every(w => hay.includes(w));
    });
}

// Пропуск в тексте пасты — подчёркивание: «По адресу _ на Ваш _…». После
// вставки окно выделяет первый, чтобы его можно было сразу перепечатать.
export function firstBlank(text, from = 0) {
    const i = String(text).indexOf('_', from);
    return i < 0 ? null : { start: i, end: i + 1 };
}

