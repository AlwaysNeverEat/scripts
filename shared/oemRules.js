// Что известно о моторе, когда допусков нет: правила «марка + годы + топливо».
//
// ЗАЧЕМ ЭТОТ ФАЙЛ
// У 2649 машин из 13391 (каждая пятая) `car_approvals` пуст — источник ничего
// не отдал. Раньше для них подбор шёл вслепую: класс не выводился вообще, и
// калькулятор предлагал самое дешёвое густое масло вязкости — одно и то же
// 2040 машинам подряд, от Mercedes-Benz с сажевым фильтром до Toyota под ILSAC.
// Между тем марку, год начала выпуска и (почти всегда) топливо мы знаем
// достоверно: это поля самой машины, а не паспорт чужого масла. По ним завод
// и сам определяет требование к маслу — допуск меняется не от машины к машине,
// а от поколения к поколению.
//
// ЧТО ЗДЕСЬ ЛЕЖИТ
// Таблица правил «марка (+ годы, + топливо) → допуск, который завод требовал
// в эту эпоху». Правило отдаёт ОБЫЧНЫЕ СТРОКИ ДОПУСКОВ — те же, что приходят
// из базы. Дальше их разбирает `shared/approvals.js` тем же кодом, что и
// настоящие: физика, ранги, совместимость с маслом считаются одинаково.
// Отдельной ветки «подбор без допусков» не появляется — появляется ещё один
// источник тех же допусков, только с меньшим доверием.
//
// ГРАНИЦА ОТВЕТСТВЕННОСТИ (главное правило, чтобы не конфликтовать с данными)
//   • Правило отвечает за ЖЕЛЕЗО: какая эпоха, есть ли сажевый фильтр, что
//     завод требовал для этого поколения. Это свойство машины.
//   • Допуска из базы отвечают за то, ЧЕМ это требование закрыть.
// Поэтому: правило применяется как требование ТОЛЬКО там, где родного допуска
// марки не нашлось ни в списке машины, ни в рекомендации Motul. Нашёлся
// родной допуск — он точнее любой эпохи, и правило молчит (см. `applied` в
// `analyzeCarApprovals`). Единственное, что правило говорит всегда, — поле
// `filter`: наличие сажевого фильтра от списка допусков не зависит вообще.
//
// ЧЕГО ЗДЕСЬ СОЗНАТЕЛЬНО НЕТ
// Правил «на всякий случай». Сомнительное совпадение хуже пустого поля: если
// у марки требование зависит от конкретного мотора (Fiat, Jaguar, SsangYong,
// китайские марки), правила для неё нет — машина останется на прежнем
// поведении, а не получит выдуманный допуск. Список непокрытого — в
// docs/DOPUSKI.md, §10.
// ─────────────────────────────────────────────────────────────────────────────

