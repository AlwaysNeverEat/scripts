// Нарезка знамён факультетов: присланный лист (четыре полосы с рваными
// краями, сверху вниз — Гриффиндор, Когтевран, Пуффендуй, Слизерин) →
// четыре обложки для шапки профиля.
//
// Делает три вещи:
//
// 1. НАХОДИТ полосы по альфе, а не по жёстким координатам: лист рисованный,
//    полосы стоят неровно, и перерисованный лист не должен требовать правки
//    границ полос в скрипте.
// 2. ВЫРЕЗАЕТ из полосы ПОЛНОСТЬЮ НЕПРОЗРАЧНЫЙ прямоугольник. Рваный край —
//    украшение листа, а не обложки: шапка профиля залита картинкой до краёв
//    (background-size: cover, скругление режет сама карточка), и прозрачные
//    зазубрины показывали бы сквозь себя градиент-подложку грязной бахромой.
// 3. УЖИМАЕТ полосу ПО СОДЕРЖАНИЮ, а не масштабом. Лист рисован ~13.7:1, а
//    шапка профиля ~7.9:1 (758×96) — cover по высоте показывал бы только
//    середину, один замок без зверя и герба. Поэтому из полосы берутся ТРИ
//    куска — зверь, замок, натюрморт с гербом, — а драпировка и холмы между
//    ними выбрасываются; стыки сшиваются плавным перетеканием по «тихим»
//    местам (ткань, небо), где глазу не за что зацепиться. Координаты кусков
//    подобраны руками под этот source.png (см. SEGMENTS) — перерисованный
//    лист потребует перемерить их, скрипт это скажет проверкой границ.
//
// Уменьшения масштабом нет сознательно: высота полосы (~130px) и так меньше,
// чем нужно шапке на retina (96px × 2), картинка тянется вверх — резать
// разрешение значит мылить сильнее.
//
// Чтение, запись и усреднение берём у ресайзера иконок игр
// (design/game-icons/resize.mjs) — второй PNG-кодек в репозитории не нужен.
//
// Запуск: node design/faculty-covers/prepare.mjs

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readPng, writePng } from '../game-icons/resize.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT_DIR = path.resolve(HERE, '../../frontend/src/assets');

// Порядок полос на листе, сверху вниз.
const ORDER = ['gryffindor', 'ravenclaw', 'hufflepuff', 'slytherin'];

// Куски полосы, которые остаются в обложке: [от, до) в координатах УЖЕ
// ВЫРЕЗАННОГО непрозрачного прямоугольника (~1780 шириной). Между соседними
// кусками — перетекание шириной BLEND, поэтому границы стоят в ткани и небе,
// а не по зверю. Целились в итоговые ~8:1: чуть шире шапки — по бокам
// остаётся маленький запас под кроп, чуть уже — cover срежет пару пикселей
// сверху и снизу, и то и другое незаметно.
const SEGMENTS = {
    gryffindor: [[40, 515], [850, 1170], [1340, 1777]],  // лев · замок · щит и книга
    ravenclaw:  [[240, 545], [880, 1270], [1375, 1780]], // орёл · замок с луной · книги и щит
    hufflepuff: [[130, 545], [870, 1190], [1395, 1786]], // барсук со щитом · замок с виадуком · шарф и фонарь
    slytherin:  [[20, 515], [840, 1130], [1330, 1782]],  // змея со щитом · замок над озером · щит и зелья
};

// Ширина перетекания на стыке. Уже — виден шов, шире — двоится рисунок;
// 70px на итоговой ширине ~1100 — это мягкая тень на пару миллиметров экрана.
const BLEND = 70;

// Плавная S-кривая вместо линейной: у линейного перетекания видны обе резкие
// границы полосы смешивания, у smoothstep края сходят на нет.
const smooth = (t) => t * t * (3 - 2 * t);

// Сшить куски полосы {w, h, px} в одну картинку с перетеканием на стыках.
// Соседние куски кладутся внахлёст на BLEND: правый край предыдущего угасает
// ровно там, где набирает силу левый край следующего.
function stitch(strip, segments) {
    const { w, h, px } = strip;
    for (const [a, b] of segments) {
        if (!(a >= 0 && b > a + BLEND && b <= w)) {
            throw new Error(`кусок [${a}, ${b}) не влезает в полосу шириной ${w} — лист перерисован? перемерь SEGMENTS`);
        }
    }
    const outW = segments.reduce((s, [a, b]) => s + (b - a), 0) - BLEND * (segments.length - 1);
    const out = Buffer.alloc(outW * h * 4);
    let at = 0; // куда в out ложится левый край очередного куска
    segments.forEach(([a, b], i) => {
        const sw = b - a;
        for (let y = 0; y < h; y++) {
            for (let x = 0; x < sw; x++) {
                const src = ((y * w) + a + x) * 4;
                const dst = ((y * outW) + at + x) * 4;
                // В зоне нахлёста подмешиваемся к уже записанному соседу.
                const k = i > 0 && x < BLEND ? smooth(x / BLEND) : 1;
                for (let c = 0; c < 4; c++) {
                    out[dst + c] = Math.round(px[src + c] * k + out[dst + c] * (1 - k));
                }
            }
        }
        at += sw - BLEND;
    });
    return { w: outW, h, px: out };
}

// «Полностью непрозрачный» — с запасом: по самому краю рисунка альфа доходит
// до 255 не везде, и строгое === 255 съедало бы лишние строки.
const OPAQUE = 250;

const sheet = readPng(fs.readFileSync(path.join(HERE, 'source.png')));
const { w, h, px } = sheet;
const alpha = (x, y) => px[(y * w + x) * 4 + 3];

// Полоса — подряд идущие строки, где заполнена хотя бы треть ширины (края
// листа рваные, поэтому порог не «вся строка»).
const bands = [];
let start = -1;
for (let y = 0; y <= h; y++) {
    let filled = 0;
    if (y < h) for (let x = 0; x < w; x++) if (alpha(x, y) > 8) filled++;
    const inBand = y < h && filled > w / 3;
    if (inBand && start < 0) start = y;
    if (!inBand && start >= 0) { bands.push([start, y - 1]); start = -1; }
}
if (bands.length !== ORDER.length) {
    throw new Error(`ожидалось ${ORDER.length} полос, найдено ${bands.length}`);
}

for (let i = 0; i < bands.length; i++) {
    const [y0, y1] = bands[i];

    // Сначала левый и правый край: пересечение непрозрачных диапазонов по
    // строкам, которые заполнены почти целиком (крайние ряды полосы рваные и
    // в счёт не идут — они бы сдвинули края внутрь на всю свою зазубрину).
    let x0 = 0, x1 = w - 1;
    for (let y = y0; y <= y1; y++) {
        let l = 0, r = w - 1;
        while (l < w && alpha(l, y) < OPAQUE) l++;
        while (r > l && alpha(r, y) < OPAQUE) r--;
        if (r - l < w * 0.9) continue;
        if (l > x0) x0 = l;
        if (r < x1) x1 = r;
    }

    // Потом верх и низ: строки, непрозрачные на всей выбранной ширине.
    let t = -1, b = -1;
    for (let y = y0; y <= y1; y++) {
        let ok = true;
        for (let x = x0; x <= x1; x++) if (alpha(x, y) < OPAQUE) { ok = false; break; }
        if (ok && t < 0) t = y;
        if (ok) b = y;
    }
    if (t < 0) throw new Error(`полоса ${ORDER[i]}: не нашлось полностью непрозрачных строк`);

    const cw = x1 - x0 + 1, ch = b - t + 1;
    const out = Buffer.alloc(cw * ch * 4);
    for (let y = 0; y < ch; y++) {
        px.copy(out, y * cw * 4, ((y + t) * w + x0) * 4, ((y + t) * w + x0 + cw) * 4);
    }
    const stitched = stitch({ w: cw, h: ch, px: out }, SEGMENTS[ORDER[i]]);
    const png = writePng(stitched);
    const file = path.join(OUT_DIR, `faculty-cover-${ORDER[i]}.png`);
    fs.writeFileSync(file, png);
    console.log(`${ORDER[i]}: полоса ${y0}–${y1}, ${cw}×${ch} → ${stitched.w}×${stitched.h}`
        + ` (${(stitched.w / stitched.h).toFixed(1)}:1), ${(png.length / 1024).toFixed(0)} КБ`);
}
