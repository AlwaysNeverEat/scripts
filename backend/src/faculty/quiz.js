// ── Детерминированный порядок вопросов и вариантов ───────────────────────────
// Свой у каждого аккаунта и НЕ МЕНЯЮЩИЙСЯ между заходами: тест прерывают
// звонком, и вернуться человек должен на тот же вопрос, а не на «похожий».

function rngFrom(seed) {
    // 32 бита из sha256 — достаточно: перемешиваем списки из четырёх-девяти
    // элементов, а не тасуем колоду на деньги.
    let state = createHash('sha256').update(seed).digest().readUInt32BE(0) || 0x9e3779b9;
    return () => {
        state ^= (state << 13); state >>>= 0;
        state ^= (state >>> 17);
        state ^= (state << 5);  state >>>= 0;
        return state / 0x1_0000_0000;
    };
}

function shuffled(list, seed) {
    const out = list.slice();
    const rnd = rngFrom(seed);
    for (let i = out.length - 1; i > 0; i--) {
        const j = Math.floor(rnd() * (i + 1));
        [out[i], out[j]] = [out[j], out[i]];
    }
    return out;
}

/**
 * Вопросы для клиента: тот же список, но БЕЗ весов и в своём для каждого
 * аккаунта порядке. Блоки идут как заданы (это сценарий теста), перемешивается
 * только внутренность блока и порядок вариантов.
 */
export function publicQuestions(userId) {
    const out = [];
    for (const section of SECTIONS) {
        const inSection = QUESTIONS.filter(q => q.section === section.id);
        for (const q of shuffled(inSection, `faculty-q:${userId}:${section.id}`)) {
            const base = { id: q.id, section: q.section, type: q.type, text: q.text };
            if (q.type === 'scale') {
                out.push({ ...base, labels: SCALE_LABELS });
            } else if (q.type === 'order') {
                out.push({
                    ...base,
                    items: shuffled(q.items, `faculty-o:${userId}:${q.id}`).map(i => ({ id: i.id, text: i.text })),
                });
            } else {
                out.push({
                    ...base,
                    options: shuffled(q.options, `faculty-o:${userId}:${q.id}`).map(o => ({ id: o.id, text: o.text })),
                });
            }
        }
    }
    return out;
}

// ── Ответы ───────────────────────────────────────────────────────────────────

/**
 * Проверка и приведение одного ответа к каноническому виду.
 * Возвращает null, если ответ не подходит вопросу: значение из тела запроса
 * попадёт в базу и через неделю в подсчёт, поэтому мусор отсекаем на входе,
 * а не «как-нибудь потом посчитаем».
 */
export function normalizeAnswer(questionId, value) {
    const q = BY_ID.get(questionId);
    if (!q) return null;

    if (q.type === 'scale') {
        const n = Number(value);
        if (!Number.isInteger(n) || n < 0 || n >= SCALE_LABELS.length) return null;
        return n;
    }
    if (q.type === 'order') {
        if (!Array.isArray(value) || value.length !== q.items.length) return null;
        const ids = q.items.map(i => i.id);
        // Ровно перестановка: без повторов и без чужих пунктов.
        if (new Set(value).size !== value.length) return null;
        if (!value.every(id => ids.includes(id))) return null;
        return value.slice();
    }
    return q.options.some(o => o.id === value) ? value : null;
}

// Вклад одного ответа в шкалы.
function contribution(q, answer) {
    const add = { courage: 0, ambition: 0, intellect: 0, loyalty: 0 };
    if (q.type === 'scale') {
        // 0…4 → −2…+2: «как когда» (2) не двигает ничего.
        const k = answer - 2;
        for (const axis of AXIS_IDS) add[axis] = q.w[axis] * k;
        return add;
    }
    if (q.type === 'order') {
        answer.forEach((itemId, pos) => {
            const item = q.items.find(i => i.id === itemId);
            for (const axis of AXIS_IDS) add[axis] += item.w[axis] * ORDER_WEIGHTS[pos];
        });
        return add;
    }
    const opt = q.options.find(o => o.id === answer);
    for (const axis of AXIS_IDS) add[axis] = opt.w[axis];
    return add;
}

// ── Общая мерка для четырёх шкал ─────────────────────────────────────────────
// Шкалы набираются разным числом вопросов и разными весами, поэтому «сырые»
// суммы несравнимы: без приведения к общей мерке тот, у кого вопросов больше,
// один решал бы за человека.
//
// Приводим НЕ к теоретическому максимуму («все тридцать ответов подряд в одну
// сторону»), а к РАЗБРОСУ: сколько эта шкала гуляет, если отвечать наугад.
// Максимум недостижим — до него не доходит никто, и шкала, у которой он выше,
// в итоге всегда выглядела бы бледнее соседней. Разброс же показывает, что для
// этой шкалы значит «сильно в плюс» на самом деле.
//
// Считаем его точно, а не прогоном случайных ответов: вклад каждого вопроса —
// независимая случайная величина с известным распределением, дисперсии
// складываются.
function questionVariance(q, axis) {
    if (q.type === 'scale') {
        // Равномерный ответ 0…4 даёт множитель −2…+2, E[k]=0, E[k²]=2.
        return (q.w[axis] ** 2) * 2;
    }
    if (q.type === 'order') {
        // Случайная перестановка: дисперсия суммы w·m равна
        // Σ(w−w̄)² · Σ(m−m̄)² / (n−1) — известная формула для выборки без возврата.
        const ws = q.items.map(i => i.w[axis]);
        const mean = ws.reduce((s, v) => s + v, 0) / ws.length;
        const ss = ws.reduce((s, v) => s + (v - mean) ** 2, 0);
        const mm = ORDER_WEIGHTS.reduce((s, v) => s + v * v, 0);
        return ss * mm / (ws.length - 1);
    }
    const ws = q.options.map(o => o.w[axis]);
    const mean = ws.reduce((s, v) => s + v, 0) / ws.length;
    return ws.reduce((s, v) => s + (v - mean) ** 2, 0) / ws.length;
}

const AXIS_SD = Object.fromEntries(AXIS_IDS.map(axis => [
    axis,
    Math.sqrt(QUESTIONS.reduce((sum, q) => sum + questionVariance(q, axis), 0)),
]));

// 100 очков шкалы = три её сигмы. Дальше ±100 уехать можно, и это нормально:
// так и должен выглядеть человек, который тридцать раз подряд ответил в одну
// сторону. Обрезать такой результат нельзя — именно у него самый ясный
// характер, и обрезка сдвинула бы его к чужому эталону.
const AXIS_SPAN = 3;

/**
 * Итоговые координаты по ответам. answers — { questionId: значение }.
 * Неотвеченные вопросы просто не учитываются: считать «пропущено = середина»
 * нечестно, а finish всё равно не даст закончить с дырками.
 */
export function scoreAnswers(answers) {
    const raw = { courage: 0, ambition: 0, intellect: 0, loyalty: 0 };
    for (const [id, value] of Object.entries(answers || {})) {
        const q = BY_ID.get(id);
        if (!q) continue;                                  // вопрос убрали из теста
        const answer = normalizeAnswer(id, value);
        if (answer === null) continue;                     // мусор в базе не должен ронять подсчёт
        const add = contribution(q, answer);
        for (const axis of AXIS_IDS) raw[axis] += add[axis];
    }
    const scores = {};
    for (const axis of AXIS_IDS) {
        scores[axis] = Math.round((raw[axis] / (AXIS_SD[axis] * AXIS_SPAN)) * 100);
    }
    return scores;
}

/**
 * Ближайший эталон. Расстояние обычное евклидово по четырём шкалам — все
 * равноправны: нет «главной», которая одна решала бы за человека.
 *
 * Ничью (двое ровно на одном расстоянии — на практике почти невозможно)
 * разрешаем порядком факультетов в shared/faculties.js: результат обязан быть
 * воспроизводимым, а не зависеть от того, как перебрались ключи объекта.
 */
export function pickFaculty(scores) {
    let best = null;
    let bestDist = Infinity;
    for (const id of FACULTY_IDS) {
        const proto = PROTOTYPES[id];
        if (!proto) continue;
        let d = 0;
        for (const axis of AXIS_IDS) {
            const diff = (scores[axis] || 0) - proto[axis];
            d += diff * diff;
        }
        if (d < bestDist) { bestDist = d; best = id; }
    }
    return best;
}

export function facultyFromAnswers(answers) {
    const scores = scoreAnswers(answers);
    return { scores, faculty: pickFaculty(scores) };
}

