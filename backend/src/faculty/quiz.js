// ─────────────────────────────────────────────────────────────────────────────
// Распределение по факультетам Хогвартса: сам опросник, шкалы и подсчёт.
//
// ГЛАВНОЕ ПРАВИЛО ЭТОГО ФАЙЛА: он никогда не уезжает в браузер. Клиенту
// отдаётся publicQuestions() — те же вопросы, но БЕЗ весов, а считает ответы
// сервер по сохранённым в базе выборам. Иначе тест превращается в «открой
// исходники и собери себе Гриффиндор», а факультет должен быть про человека.
//
// Вопросы НЕ про работу — обычные житейские развилки: кошелёк на улице,
// очередь, шумные соседи, лишняя сдача. Так и задумано: тест проходят один раз
// в жизни аккаунта, и он про характер, а не про должность. Рабочие ситуации
// пришлось бы описывать чужими словами, и первый же человек, который правда
// стоит на посту, узнал бы в них выдумку.
//
// Почему не «каждый ответ — это факультет»
// ────────────────────────────────────────
// В тесте, где вариант «а» — Гриффиндор, а вариант «б» — Слизерин, человек уже
// на третьем вопросе понимает раскладку и дальше отвечает не про себя, а про
// желаемый результат. Поэтому ответы вообще НЕ ЗНАЮТ про факультеты. Каждый
// вариант двигает четыре независимые ШКАЛЫ — те самые качества из канона:
//
//   courage   (+) смелость, прямота, «я скажу»   ↔ (−) осторожность, тишина
//   ambition  (+) амбиция, расчёт, своя выгода   ↔ (−) скромность, «и так хорошо»
//   intellect (+) разобраться, понять, придумать ↔ (−) сделать и не забивать голову
//   loyalty   (+) свои, помощь, доброта, труд    ↔ (−) сам за себя
//
// Факультет появляется только в самом конце: итоговая точка сравнивается с
// четырьмя эталонами, побеждает ближайший. Один и тот же ответ работает на
// разные факультеты в зависимости от остальных — угадать по ходу нечего.
// Храбрый и амбициозный уйдёт в Гриффиндор или в Слизерин В ЗАВИСИМОСТИ от
// того, что он ответил про своих, а не от одного «смелого» варианта.
//
// Что сделано ради честности результата
// ─────────────────────────────────────
// 1. Каждый вопрос с вариантами УРАВНОВЕШЕН: сумма весов всех его вариантов по
//    каждой шкале равна нулю (это проверяет quiz.test.js). Значит, сам набор
//    вариантов никуда не тянет — тянет только выбор человека.
// 2. Вес у варианта либо ЕСТЬ, либо НЕТ: только −1, 0 или +1, никаких
//    полутонов. Это главный урок первой версии, и он стоил четверых первых
//    прошедших — см. «Как этот тест уже один раз сломался» ниже.
// 3. Варианты внутри вопроса устроены решёткой: вопрос берёт ДВЕ шкалы, и
//    четыре варианта — это четыре сочетания «+/+», «+/−», «−/+», «−/−».
//    Отсюда и баланс сам собой, и отсутствие вариантов-пустышек.
// 4. Утверждения блока «Про себя» идут парами «за» и «против» по каждой шкале,
//    поэтому тот, кто соглашается со всем подряд, не уезжает никуда: его
//    ответы просто перестают что-либо значить, как и должно быть.
// 5. Порядок вопросов внутри блока и порядок вариантов — свои у каждого
//    аккаунта (детерминированно от id). Двое рядом видят разные экраны, и
//    списывать не у кого; при этом свой порядок не меняется между заходами,
//    поэтому прерванный тест продолжается ровно там, где встал.
// 6. Плохих вариантов нет: везде выбирают между нормальными людьми, а не между
//    хорошим и стыдным. Где ситуация всё-таки про совесть (кошелёк, чужая
//    похвала), варианты различаются НЕ тем, порядочно ли поступит человек, а
//    тем, КАК он это сделает: поеду сам / позвоню / сдам в полицию.
// 7. Шкалы разведены между собой: если бы «амбиции» и «верность» двигались
//    всегда парой (выбрал своё — значит против своих), четыре измерения
//    схлопнулись бы в два, и четыре факультета — в два противоположных угла.
//    Поэтому в тесте есть и амбициозные варианты «для своих», и скромные «сам
//    по себе», а тест на слипание шкал стоит в quiz.test.js.
//
// Как этот тест уже один раз сломался
// ───────────────────────────────────
// В первой версии веса были ±2 у «главного» смысла варианта и ±1 в довесок —
// этими довесками удобно было доводить сумму вопроса до нуля. По уму и
// амбициям довесков оказалось 86% и 77% от всех весов, и почти все в минус:
// «пошучу», «сделаю руками», «не буду вникать» — обычные человеческие ответы,
// которые тянули ум вниз просто потому, что так сходилась арифметика.
//
// Результат: у первых четверых прошедших ум вышел от 0 до −65, ни у кого не
// плюс, а трое из четырёх получили один и тот же факультет — тот единственный,
// чей эталон смотрит в минус сразу по нескольким шкалам. Тест мерил не
// характер, а то, насколько скромно человек о себе говорит.
//
// Отсюда правила 2 и 3 выше и два теста в quiz.test.js: «весов-полутонов нет»
// и «перекос населения не сгоняет всех в один дом». Второй важнее: он
// проверяет не арифметику вопросов, а то, что даже сдвинутое по какой-то
// шкале население всё равно расходится по всем четырём домам.
//
// Длина — 33 вопроса, ~7 минут. Меньше двадцати — гадание на трёх кнопках;
// больше тридцати пяти — люди начинают кликать лишь бы закончить, и точность
// падает сильнее, чем растёт от лишних вопросов.
// ─────────────────────────────────────────────────────────────────────────────

