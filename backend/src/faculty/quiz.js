/**
 * Отпечаток опросника: меняется от любой правки вопросов, вариантов или их
 * порядка в файле. Им помечается недопройденный черновик (faculty_progress),
 * и при несовпадении черновик выбрасывается.
 *
 * Считается ОТ САМИХ ВОПРОСОВ, а не выставляется руками, ровно потому, что
 * руками её однажды забудут поднять — а цена этому тихая: id вопроса остался
 * прежним, смысл поменялся, и старый ответ уедет в подсчёт как ответ на новый
 * вопрос. Веса в отпечаток не берём: если поправили только вес, ответы
 * человека остаются осмысленными, и терять его прогресс не за что.
 */
export const QUIZ_VERSION = createHash('sha256')
    .update(QUESTIONS.map(q => [
        q.id, q.type,
        (q.type === 'order' ? q.items : q.options || []).map(o => o.id).join(','),
        q.text,
    ].join('|')).join('\n'))
    .digest('hex')
    .slice(0, 12);

// ── Эталоны факультетов ──────────────────────────────────────────────────────
// Точка каждого дома в тех же координатах, что и итог человека (шкалы приведены
// к −100…+100). Числа не круглые и не симметричные намеренно: это канонические
// качества, а не «по 25% на каждого». Проверку на то, что каждый факультет
// достижим и никто не забирает половину людей, делает quiz.test.js — трогать
// эталоны без прогона теста нельзя.
