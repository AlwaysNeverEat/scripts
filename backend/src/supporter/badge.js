// ─────────────────────────────────────────────────────────────────────────────
// Подписка «supp» — та её часть, которая НЕ ХОДИТ В БАЗУ: кто владелец, как
// присоединять подписку к спискам людей и что показывать рядом с ником.
//
// Отдельным файлом, а не в store.js, ровно по одной причине: проверять правило
// «владелец — вот этот логин» и вид плашки должно быть можно без живого
// Postgres (см. badge.test.js). Всё, что действительно ходит в базу, лежит в
// store.js и импортирует отсюда.
// ─────────────────────────────────────────────────────────────────────────────

import { normalizeTheme } from '../../../shared/supporterTheme.js';

// Кому можно выдавать подписки. Ровно один аккаунт, и он задаётся ЛОГИНОМ, а
// не ролью: модераторов несколько, а деньги за подписку принимает один
// человек, и раздача оплаченного — не модераторская работа. Env оставлен для
// смены владельца и для тестов.
export const OWNER_LOGIN = (process.env.OWNER_LOGIN || 'gtrixoff').toLowerCase();

export function isOwnerLogin(login) {
    return typeof login === 'string' && login.trim().toLowerCase() === OWNER_LOGIN;
}

/** Владелец ли это (объект пользователя из сессии). */
export function isOwner(user) {
    return Boolean(user && isOwnerLogin(user.login));
}

// ── Присоединение плашки к выдаче пользователей ──────────────────────────────
// Как FACULTY_JOIN у факультетов: плашка стоит рядом с ником в месячном топе,
// в мини-топах пасхалок и в профиле, и запрос за ней обязан быть один и тот же
// во всех местах — иначе человек увидит себя подписчиком в одном списке и без
// плашки в другом.
//
// Условие срока стоит В САМОМ JOIN, а не в WHERE, и это важно вдвойне: WHERE
// выкинул бы из топа человека, у которого подписка кончилась, — а он не
// перестал делать записи, он перестал быть подписчиком. Отсюда же и «сама
// уберётся через месяц»: истёкшая строка просто перестаёт соединяться, во всех
// списках разом и без крона, которого в проекте нет.
export const SUPPORTER_JOIN = `
  LEFT JOIN supporters sp
         ON sp.user_id = u.id
        AND (sp.expires_at IS NULL OR sp.expires_at > now())`;

export const SUPPORTER_COLUMNS = 'sp.user_id AS supp_id, sp.expires_at AS supp_expires, sp.theme AS supp_theme';

// Те же колонки для GROUP BY — месячный топ группирует строки по пользователю.
export const SUPPORTER_GROUP_BY = 'sp.user_id, sp.expires_at, sp.theme';

/**
 * Плашка подписчика для строки списка: только то, что рисуется рядом с ником.
 *
 * Цвет отдаётся вместе с плашкой не для красоты: им же красится строка
 * подписчика в топе (frontend/src/top.js), и ходить за ним отдельным запросом
 * на каждую строку было бы расточительно.
 *
 * Сломанные настройки темы (записаны старой версией окна, поправлены руками в
 * psql) плашку НЕ уносят: подписка оплачена, а цвет всегда есть — испорченный
 * заменяется значением по умолчанию.
 */
export function supporterBadge(row) {
    if (!row || !row.supp_id) return null;
    const theme = normalizeTheme(row.supp_theme);
    return {
        label: 'supp',
        color: theme.accent,
        // Красить ли свою строку в топе — выбор самого подписчика.
        glow: theme.glow,
        until: row.supp_expires || null,
        forever: !row.supp_expires,
    };
}
