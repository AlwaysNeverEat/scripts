// Выбор месяца и список для листания. Ошибка тут выглядит не как падение, а
// как подмена: под подписью «август» показан сентябрь, или прошлый месяц
// пропал из листания и кажется удалённым.

import test from 'node:test';
import assert from 'node:assert/strict';

import { pickMonth, monthList } from './top.js';

test('без параметра — текущий месяц', () => {
    assert.equal(pickMonth(undefined, '2026-10'), '2026-10');
    assert.equal(pickMonth('', '2026-10'), '2026-10');
});

test('прошлый месяц отдаётся как есть', () => {
    assert.equal(pickMonth('2026-09', '2026-10'), '2026-09');
});

test('мусор — отказ, а не молча текущий', () => {
    for (const bad of ['2026-13', '2026-00', '2026-9', '09-2026', "2026-09' OR 1=1", ['2026-09']]) {
        assert.equal(pickMonth(bad, '2026-10'), null, String(bad));
    }
});

test('текущий месяц в списке есть всегда, даже без единой записи', () => {
    assert.deepEqual(monthList(['2026-08', '2026-09'], '2026-10'), ['2026-10', '2026-09', '2026-08']);
    assert.deepEqual(monthList([], '2026-10'), ['2026-10']);
});

test('список: свежие первыми, без повторов и без будущего', () => {
    assert.deepEqual(
        monthList(['2026-07', '2026-09', '2026-09', '2026-11', 'junk'], '2026-10'),
        ['2026-10', '2026-09', '2026-07'],
    );
});
